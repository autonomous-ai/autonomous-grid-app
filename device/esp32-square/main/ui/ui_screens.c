// Reflect the link on the UI. Green dots = grid-app is answering; muted dots + a "Not connected" badge =
// it is not. The badge shows only on the projects screen. Cheap (no animation) — safe to call every ~1s.
// Caller holds the display lock.
//
// TWO states, where the reference has three. Its ladder is WiFi-down / socket-down-but-WiFi-up /
// node-offline, and the middle one exists because a radio can be up while the backend is unreachable.
// A cable has no such middle: either grid-app has said `welcome` on it or it has not.
static void refresh_conn_ui(void)
{
    lv_color_t dotc = s_connected ? COL_GREEN : COL_MUTED;
    for (int i = 0; i < s_proj_count; i++)
        if (s_proj[i].dot) lv_obj_set_style_bg_color(s_proj[i].dot, dotc, 0);   // only windowed tiles have a dot

    if (!s_reconnect_badge) return;
    // Suppressed while the Overview is already showing the full "open Grid" guide — one screen must not
    // say the same thing twice, once as a headline and once as a badge over it.
    bool say = lv_screen_active() == scr_projects && !s_connected &&
               !(s_overview_active && s_remote_offline_view);
    if (say) {
        lv_label_set_text(s_reconnect_badge, "Not connected");
        lv_obj_set_style_text_color(s_reconnect_badge, COL_MUTED, 0);
        lv_obj_clear_flag(s_reconnect_badge, LV_OBJ_FLAG_HIDDEN);
    } else {
        lv_obj_add_flag(s_reconnect_badge, LV_OBJ_FLAG_HIDDEN);
    }
}

// The top status bar (wifi · time · battery) was removed from the design — battery now lives as a row
