// Claude-Code-style rotating gerunds for the working-status verb row (ASCII only → font renders them).
static const char *GERUNDS[] = {
    "Working", "Brewing", "Cooking", "Churning", "Frosting", "Simmering", "Tinkering",
    "Conjuring", "Composing", "Percolating", "Wrangling", "Hatching", "Concocting", "Puttering",
};
#define N_GERUNDS ((int)(sizeof(GERUNDS) / sizeof(GERUNDS[0])))

// "34s" or "1m 05s"
static void fmt_elapsed(int64_t s, char *out, size_t cap)
{
    if (s < 60) snprintf(out, cap, "%llds", (long long)s);
    else        snprintf(out, cap, "%lldm %02llds", (long long)(s / 60), (long long)(s % 60));
}
// No token formatter. The reference prints a running output-token count beside the elapsed time, fed by
// a backend field; grid-app sends no such number, and a counter stuck at zero is worse than no counter.

// Refresh a project's working-status verb line (Figma "working"): a single green "<verb> <elapsed>" label
// (e.g. "Cooking… 34s"). The grey teaser below is the last recap, set once in render_busy_row (unchanged here).
static void busy_compose(proj_t *p)
{
    if (!p->busy_verb) return;
    int64_t sec = (esp_timer_get_time() - p->busy_since) / 1000000LL;
    if (sec < 0) sec = 0;
    char el[24]; fmt_elapsed(sec, el, sizeof(el));
    const char *verb = p->busy_step[0] ? p->busy_step : GERUNDS[(sec / 6) % N_GERUNDS];
    lv_label_set_text_fmt(p->busy_verb, "%s\xE2\x80\xA6 %s", verb, el);   // Reading file… 34s
}

// Tick the "Sending…" upload dots + the active project's working-status rows (verb rotates ~6s,
// elapsed each 1s). Runs a few times/second; the status text is only re-set when the second changes.
// The floating mic is a pure STATUS INDICATOR now (voice is driven by gestures: double-tap starts, a
// tap stops — see touch.c). Shown only during a live turn: the red mic while recording, the spinner
// while the clip uploads; hidden otherwise (and while asleep). Reads s_vic_state; caller holds the lock.
static void voice_btn_apply_visibility(void)
{
    if (!s_wave[0] || !s_send_sp[0]) return;
    bool sending   = (s_vic_state == VIC_SEND);
    bool recording = (s_vic_state == VIC_MIC || s_vic_state == VIC_REC);
    bool show = !display_is_asleep() && (recording || sending);
    for (int i = 0; i < 7; i++) set_hidden(s_wave[i],    !show || !recording);  // green waveform: recording only
    for (int i = 0; i < 3; i++) set_hidden(s_send_sp[i], !show || !sending);    // sparkles: uploading only
    if (s_voice_img) set_hidden(s_voice_img, true);   // legacy orb retired
}
// One breathing halo: t 0→1000 grows the circle (84→124px) and brightens it (55→120), then the anim's
// playback shrinks/dims it back — a soft glow that pulses in and out (not a sonar ripple). We animate the
// REAL size (a direct circle fill), NOT transform_scale / style opa — those snapshot the object to an
// oversized temp layer each frame and OOM the LVGL draw pool (that crashed the device). bg_opa is a plain
// per-pixel alpha blend, no layer.
static void pulse_anim_cb(void *var, int32_t t)
{
    lv_obj_t *o = var;
    int32_t sz = 84 + (int32_t)((int64_t)t * (124 - 84) / 1000);   // breathe 84 ↔ 124 px
    lv_obj_set_size(o, sz, sz);
    lv_obj_align_to(o, s_voice_img, LV_ALIGN_CENTER, 0, 0);        // stay centred on the mic
    lv_obj_set_style_bg_opa(o, (lv_opa_t)(55 + (int32_t)((int64_t)t * (120 - 55) / 1000)), 0);  // 55 ↔ 120, brightest at full size
}
// Start/stop the two-circle breathing glow behind the mic/dots (on while recording or sending).
static void voice_pulse_set(bool on)
{
    for (int i = 0; i < 2; i++) {
        if (!s_pulse[i]) continue;
        lv_anim_delete(s_pulse[i], pulse_anim_cb);
        if (on) {
            set_hidden(s_pulse[i], false);
            lv_anim_t a; lv_anim_init(&a);
            lv_anim_set_var(&a, s_pulse[i]);
            lv_anim_set_exec_cb(&a, pulse_anim_cb);
            lv_anim_set_values(&a, 0, 1000);
            lv_anim_set_duration(&a, 1400);
            lv_anim_set_playback_time(&a, 1400);      // grow AND shrink → a breathing halo
            lv_anim_set_repeat_count(&a, LV_ANIM_REPEAT_INFINITE);
            lv_anim_set_path_cb(&a, lv_anim_path_ease_in_out);
            if (i == 1) lv_anim_set_delay(&a, 700);   // 2nd circle out of phase → layered, continuous glow
            lv_anim_start(&a);
        } else {
            set_hidden(s_pulse[i], true);
            lv_obj_set_style_bg_opa(s_pulse[i], 0, 0);
        }
    }
}
// Start/stop the 3-dot "typing" upload indicator: each dot's opacity pulses 60↔255, staggered 160ms → a
// sequential bounce. Runs while the clip uploads (VIC_SEND).
static void dot_anim_cb(void *var, int32_t v) { lv_obj_set_style_bg_opa((lv_obj_t *)var, (lv_opa_t)v, 0); }
static void voice_dots_set(bool on)
{
    for (int i = 0; i < 3; i++) {
        if (!s_send_dots[i]) continue;
        lv_anim_delete(s_send_dots[i], dot_anim_cb);
        if (on) {
            set_hidden(s_send_dots[i], false);
            lv_anim_t a; lv_anim_init(&a);
            lv_anim_set_var(&a, s_send_dots[i]);
            lv_anim_set_exec_cb(&a, dot_anim_cb);
            lv_anim_set_values(&a, 60, 255);
            lv_anim_set_duration(&a, 450);
            lv_anim_set_playback_time(&a, 450);
            lv_anim_set_repeat_count(&a, LV_ANIM_REPEAT_INFINITE);
            lv_anim_set_delay(&a, i * 160);           // stagger → the three dots bounce in sequence
            lv_anim_set_path_cb(&a, lv_anim_path_ease_in_out);
            lv_anim_start(&a);
        } else {
            set_hidden(s_send_dots[i], true);
        }
    }
}
// Figma "Section final" waveform: 7 vertical rounded bars, symmetric rest heights, pulsing to a travelling
// wave. We drive it from ONE ~25 Hz timer computing each bar's height from a shared travelling phase (NOT
// per-bar lv_anim with a leading delay — that applied the collapsed start value to every bar at once and let
// them sit short for ~1 cycle before the stagger established, which looked janky on entry). Here every bar is
// already at a distinct phase on the very first frame, so it's smooth immediately. REAL height (and re-centre)
// each frame — never transform_scale, which snapshots to an oversized temp layer and OOMs the LVGL draw pool.
// Figma drew these 1:1 for the 466px round panel. Back to essentially those numbers here (x480/466),
// NOT the 720px board's — the waveform is a fixed overlay measured against the panel, and this panel is
// the round one's size. Carrying the 1.55x version over would have put a 187px bar on a 480px screen.
static const int16_t s_wave_rest[7] = { 17, 54, 81, 125, 81, 54, 17 };   // 16,52,79,121,… @466
static lv_timer_t *s_wave_timer;
static int16_t     s_wave_phase;   // degrees; advances each tick so the crest travels left→right
static void wave_tick(lv_timer_t *t)
{
    (void)t;
    s_wave_phase += 12;                                   // 12°/40ms → ~1.2s per full cycle
    if (s_wave_phase >= 360) s_wave_phase -= 360;
    for (int k = 0; k < 7; k++) {
        if (!s_wave[k]) continue;
        int16_t ang = (int16_t)((s_wave_phase + k * 40) % 360);   // 40° phase step per bar → travelling wave
        int32_t s   = lv_trigo_sin(ang);                          // -32767..32767
        int32_t amp = 675 + (s * 325 / 32767);                    // permille 350..1000 → 0.35×..1.0× rest
        int32_t h   = (int32_t)s_wave_rest[k] * amp / 1000;
        if (h < 2) h = 2;
        lv_obj_set_height(s_wave[k], h);
        lv_obj_set_y(s_wave[k], SCR_CY - h / 2);             // stay centred on the midline as it grows/shrinks
    }
}
// Start/stop the waveform: spin up the shared travelling-phase timer and seed one frame immediately (so nothing
// is collapsed on show); tear it down when we leave the recording state.
static void voice_wave_set(bool on)
{
    if (on) {
        // Waveform stays green for every capture; the banner alone says which command is riding along.
        for (int k = 0; k < 7; k++) if (s_wave[k]) set_hidden(s_wave[k], false);
        if (s_voice_goal_lbl) {
            set_hidden(s_voice_goal_lbl, s_voice_cmd == VOICE_CMD_NONE);
            // Text AND colour are decided HERE, per capture — not once at build time. Both come off the
            // same test so the banner always matches the pill that was pressed (amber target, blue repeat).
            if (s_voice_cmd != VOICE_CMD_NONE) {
                bool goal = (s_voice_cmd == VOICE_CMD_GOAL);
                lv_label_set_text(s_voice_goal_lbl, goal ? "GOAL" : "LOOP");
                lv_obj_set_style_text_color(s_voice_goal_lbl, goal ? COL_ORANGE : COL_ACCENT, 0);
            }
        }
        if (!s_wave_timer) s_wave_timer = lv_timer_create(wave_tick, 40, NULL);
        wave_tick(s_wave_timer);   // paint the first frame now → smooth from frame 1
    } else {
        if (s_wave_timer) { lv_timer_delete(s_wave_timer); s_wave_timer = NULL; }
        for (int k = 0; k < 7; k++) if (s_wave[k]) set_hidden(s_wave[k], true);
        if (s_voice_goal_lbl) set_hidden(s_voice_goal_lbl, true);
    }
}
// Paint the 3 sending sparkles: the s_send_idx one green + popped (scale 1.3), the other two idle white.
static void voice_send_apply_idx(void)
{
    for (int i = 0; i < 3; i++) {
        if (!s_send_sp[i]) continue;
        bool active = (i == s_send_idx);
        lv_obj_set_style_image_recolor(s_send_sp[i], active ? COL_VOICE : COL_SPARK_OFF, 0);
        lv_image_set_scale(s_send_sp[i], active ? 333 : 256);   // native 40px base (256); active pops ~1.3× (333)
    }
}
// Show/hide the 3 sending sparkles; the green highlight is marched across them by busy_dots_tick.
static void voice_send_set(bool on)
{
    if (on) s_send_idx = 0;
    for (int i = 0; i < 3; i++) {
        if (!s_send_sp[i]) continue;
        set_hidden(s_send_sp[i], !on);
    }
    if (on) voice_send_apply_idx();
}
// Show the voice indicator: the green waveform while recording, the 3 sweeping sparkles while sending; hidden
// otherwise. The legacy orb / blue glow / white dots are retired (kept created but permanently hidden). Caller
// holds the display lock.
static void voice_icon_apply(voice_icon_state_t st)
{
    s_vic_state = st;
    if (!s_wave[0] || !s_send_sp[0]) return;
    bool recording = (st == VIC_MIC || st == VIC_REC);
    bool sending   = (st == VIC_SEND);
    // Retire the old orb + glow + white dots entirely (kept created but always hidden).
    if (s_voice_img) set_hidden(s_voice_img, true);
    voice_pulse_set(false);
    voice_dots_set(false);
    voice_wave_set(recording);                     // green waveform while recording
    voice_send_set(sending);                        // sweeping sparkles while uploading
    voice_btn_apply_visibility();
}
// mic → recording after a brief beat (only if we're still in the mic state, i.e. still recording).
static void vic_to_rec_cb(lv_timer_t *t) { if (s_vic_state == VIC_MIC) voice_icon_apply(VIC_REC); lv_timer_delete(t); }

static void busy_dots_tick(lv_timer_t *t)
{
    (void)t;
    // Voice send finished (spinner up, upload no longer active) → back to the idle (hidden) indicator.
    // EXCEPT a route (Overview) voice: after the upload the router is still picking an agent, so we KEEP the
    // loading overlay/sparkles up (fall to the else branch → the sweep keeps animating) until voice_routed
    // arrives — or a watchdog releases it. That way the user never sees a static Overview mid-route.
    if (s_vic_state == VIC_SEND && !voice_active() && !s_voice_routing) {
        voice_icon_apply(VIC_NONE);
        voice_overlay_set(false);   // upload finished → restore tile content + hide the voice overlay
    } else {
        // Route voice: mark the moment the upload finished and hold the loading state until the router
        // answers; if it never does (STT/LLM failure with no terminal frame), release after the budget.
        if (s_voice_routing && s_vic_state == VIC_SEND && !voice_active()) {
            if (!s_voice_route_ms) s_voice_route_ms = lv_tick_get();
            if (lv_tick_elaps(s_voice_route_ms) > VOICE_ROUTE_WAIT_MS) {
                s_voice_routing = false; s_voice_route_ms = 0;
                voice_icon_apply(VIC_NONE);
                voice_overlay_set(false);
            }
        }
        // Mic capture ended (manual stop / buffer full) while the UI still shows the mic — audio stays
        // active through the upload, so flip to the "Sending…" spinner.
        if (ui_voice_is_recording() && voice_active() && !voice_recording()) {
            voice_icon_apply(VIC_SEND);
        }
        // Watchdog: auto-stop a forgotten recording after 10 min. All turn voices now STREAM live (no 2-min
        // buffer cap) and support long "ramble" input; ask-mode is buffered but self-limits at BUF_MAX (~2 min).
        if (ui_voice_is_recording() && lv_tick_elaps(s_voice_start_ms) > s_voice_max_ms) ui_voice_stop();
        // Silence gate (off — see VOICE_SILENCE_AUTOSTOP): a press with no speech in the first 15s used to be
        // discarded here. Only the 10-minute watchdog above stops a forgotten recording now.
        else if (VOICE_SILENCE_AUTOSTOP && ui_voice_is_recording()
                 && lv_tick_elaps(s_voice_start_ms) > VOICE_SILENCE_MS && !voice_heard())
            ui_voice_discard_silent();
        voice_btn_apply_visibility();   // keep the indicator's visibility fresh (~3 Hz)
        // Sending: march the green highlight across the 3 sparkles (~3 Hz ≈ Figma's 0.8s/3 sweep).
        if (s_vic_state == VIC_SEND) { s_send_idx = (s_send_idx + 1) % 3; voice_send_apply_idx(); }
        notif_bell_apply();            // keep the unread pill in sync (screen/settings/asleep)
    }
    // Keep the screen awake through a voice turn: voice uses the PWR key (not the touchscreen), so
    // recording + upload + the agent working produces NO touch and the idle timer would auto-off the
    // screen mid-task. Count "recording/uploading" and "the visible tile's turn is still processing" as
    // activity so the screen stays on until ~IDLE_MS after the turn actually ends.
    if (voice_active() || s_voice_routing ||
        (s_active_idx >= 0 && s_active_idx < s_proj_count && s_proj[s_active_idx].busy_model))
        display_bump_activity();
    if (display_is_asleep() || s_overview_active) return;
    if (s_active_idx < 0 || s_active_idx >= s_proj_count) return;
    proj_t *p = &s_proj[s_active_idx];
    // Pulse the in_progress todo row's glyph (~3Hz) so the active task stands out.
    if (p->todo_active) {
        static int tphase;
        lv_obj_set_style_bg_opa(p->todo_active, (tphase++ & 1) ? LV_OPA_COVER : LV_OPA_40, 0);
    }
    if (!p->busy) return;
    // Re-render only when the elapsed second (or the visible project) changes — avoids repainting the
    // text a few times/second for no reason.
    static int64_t last_sec = -1; static int last_idx = -1;
    int64_t sec = (esp_timer_get_time() - p->busy_since) / 1000000LL;
    if (sec != last_sec || s_active_idx != last_idx) {
        last_sec = sec; last_idx = s_active_idx;
        busy_compose(p);
    }
}

