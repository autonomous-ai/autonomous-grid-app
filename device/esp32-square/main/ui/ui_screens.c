// An EMPTY machine (0 agents) never goes through add_proj — which sizes the huge spacer AND jumps the scroll
// to the middle of the range (CAROUSEL_M/2). Without that, the carousel sits pinned at the spacer's LEFT
// EDGE (4 fixed tiles at columns 0..3): no room to swipe left, no infinite loop. Set it up like a non-empty
// machine: assert the huge scroll range, then park the "No agents" page (ring RING_LEAD) at CAROUSEL_M/2.
static void carousel_center_empty(void)
{
    if (s_proj_count != 0) return;
    resize_spacer();
    // Only recenter when pinned near an EDGE of the huge range (i.e. never centered yet). Once we're at
    // ~M/2, leave the user's current swipe position on the empty ring alone.
    int cc = carousel_col();
    if (cc < CAROUSEL_M / 4 || cc > CAROUSEL_M - CAROUSEL_M / 4)
        carousel_goto(col_for_ring_near(CAROUSEL_M / 2, ring_of_agent(0)), LV_ANIM_OFF);   // "No agents" page at the middle
    apply_active_from_col();
    update_content_window();
    rebuild_page_dots();
}

