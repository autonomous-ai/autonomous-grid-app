// The per-agent controls row — [engine mark] [Model] [Effort] — is the FIRST line on the tile.
//
// On the round board every number here is a compromise with the bezel: the paddings are held UNDER a true
// 1.5x because the round face is only ~305px wide at this Y, and wider pills pushed "Sonnet"+"Medium" past
// the chord and clipped their corners. The advice there is to spend slack on the GAP rather than the
// paddings, because a gap costs 2 edges and the paddings cost 6.
//
// None of that applies to a square 720px panel: the row has the full width at every Y. So these are the
// round board's values scaled by ~1.55 with the bezel caveat dropped, and the pills can breathe.
// Sized down 15% from the first pass on the real panel (owner, on hardware): the straight 1.55x scale
// made the row read as the loudest thing on the tile, when it is meant to be a quiet header above the
// agent name. Font 34 → 28 (30 exists but is only a 12% cut; 28 lands closest to the asked-for 15%),
// paddings and gap scaled to match. The engine mark follows automatically — ctl_mark_scale() derives it
// from ctl_pill_h(), so it shrinks with the pills instead of drifting out of alignment.
// Down another step now that this row is SHARED with the agent name, the bell and the gear rather than
// owning a band of its own. 28 → 22, paddings and gap cut to match: these were sized to fill a line, and
// at that size beside a 38px name they out-shout the thing they annotate. The TAP TARGET does not shrink
// with them — ui_action_hit() claims the whole press and the band is 96px tall — so the pill only has to
// be legible, not large. (LVGL ships 14/22/28/34/46/48; 22 is the step below 28.)
// Chip metrics come from the ROUND board unchanged — a chip is sized by its glyph and the finger that
// hits it. The 720px board had already converged on the same padding for the same reason.
#define CTL_CHIP_FONT   (&lv_font_montserrat_14)   // 22 @466 and @720 both
#define CTL_CHIP_PAD_H  11
#define CTL_CHIP_PAD_V  5
#define CTL_CHIP_GAP    13          // between pills
// What the right of the header reserves: gear, bell, AND the unread-count badge, which is aligned
// OUT_LEFT of the bell and grows leftward as the count gets wider. 104 covered only the two icons, so the
// first notification that arrived painted its green badge over the Effort chip.
#define HDR_RIGHT_W     93
#define HDR_NAME_GAP    9           // agent name → engine mark
#define CTL_MARK_SRC    20          // every engine icon asset is 20x20 (source asset size, not a layout px)

// Outer height of a pill: text line + its padding + the 1px border on each side.
static inline int32_t ctl_pill_h(void)
{
    return lv_font_get_line_height(CTL_CHIP_FONT) + 2 * CTL_CHIP_PAD_V + 2 /*border*/;
}

// The engine mark is sized to the PILL, not to a fixed zoom (owner, 2026-07-30): the row reads as one band
// only when the icon and the boxes share a height, and a hardcoded zoom drifts the moment the chip font or
// padding changes. Derived, so the three stay locked together.
static inline int32_t ctl_mark_scale(void)
{
    return ctl_pill_h() * 256 / CTL_MARK_SRC;   // 256 = 1:1 in LVGL
}

