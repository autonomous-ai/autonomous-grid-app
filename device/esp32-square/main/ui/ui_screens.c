bool ui_boot_pressed(void)
{
    // If the visible project is WORKING, pop a "Cancel task?" confirm (a running turn is always shown on
    // the projects screen) so an accidental press can't kill it.
    //
    // Nothing running → NOT consumed. That branch used to log "ignored" and stop there, which is the
    // whole reason the button read as unwired: on a desk panel the common state is idle, so most presses
    // landed here and did nothing at all. Returning false lets the caller spend the press on the screen.
    display_lock();
    int idx = (s_active_idx >= 0 && s_active_idx < s_proj_count) ? s_active_idx : 0;
    bool processing = (s_proj_count > 0 && !s_overview_active && s_proj[idx].busy != NULL);
    // Already asking "Cancel task?" — a second press must not re-open it. Consume so the screen does not
    // blank with a confirm dialog sitting on it.
    bool confirming = s_cancel_confirm && !lv_obj_has_flag(s_cancel_confirm, LV_OBJ_FLAG_HIDDEN);
    if (confirming) { display_unlock(); return true; }
    if (processing) {
        ESP_LOGI(TAG, "BOOT → show 'Cancel task?' confirm");
        lv_obj_clear_flag(s_cancel_confirm, LV_OBJ_FLAG_HIDDEN);
        lv_obj_move_foreground(s_cancel_confirm);
        display_unlock();
        return true;
    }
    display_unlock();
    return false;   // idle → the caller turns the screen off
}

// "Cancel task?" confirm handlers (run on the LVGL task, already under the display lock).
static void cancel_confirm_no(lv_event_t *e)
{
    (void)e;
    lv_obj_add_flag(s_cancel_confirm, LV_OBJ_FLAG_HIDDEN);
}
static void cancel_confirm_yes(lv_event_t *e)
{
    (void)e;
    lv_obj_add_flag(s_cancel_confirm, LV_OBJ_FLAG_HIDDEN);
    ui_stop_active_turn();   // the actual interrupt
}

void ui_stop_active_turn(void)
{
    display_lock();
    int idx = (s_active_idx >= 0 && s_active_idx < s_proj_count) ? s_active_idx : 0;
    bool processing = (s_proj_count > 0 && !s_overview_active && s_proj[idx].busy != NULL);
    // BY PROJECT, where the reference cancels by session. grid-app's stop takes a project id and stops
    // every conversation in it (docs/protocol.md §2) — a project can have a second chat queued behind
    // the running one, and Stop means stop. The panel also has no session id to offer: it never sees one.
    char pid[48];
    snprintf(pid, sizeof(pid), "%s", processing ? s_proj[idx].id : "");
    display_unlock();
    if (!processing || !pid[0]) return;   // nothing running → do nothing
    ESP_LOGI(TAG, "STOP → interrupt project=%s", pid);
    if (!panel_client_is_connected()) { ESP_LOGW(TAG, "stop: grid-app not connected"); return; }
    panel_client_stop_project(pid);
    // Optimistic: drop the active tile's processing row now (the killed turn won't emit a 'done'; the
    // 'stopped' ack also clears it, so this is just snappier).
    display_lock();
    if (s_proj_count > 0) clear_busy(&s_proj[idx]);
    update_stop_btn();
    display_unlock();
}

static void stop_event(lv_event_t *e)
{
    if (lv_event_get_code(e) != LV_EVENT_CLICKED) return;
    ui_stop_active_turn();
}


// --- Voice (hold-to-talk) ---

const char *ui_get_active_project_id(void)
{
    static char out[48];
    out[0] = '\0';
    display_lock();
    if (s_proj_count > 0 && !s_overview_active) {
        int idx = (s_active_idx >= 0 && s_active_idx < s_proj_count) ? s_active_idx : 0;
        snprintf(out, sizeof(out), "%s", s_proj[idx].id);
    }
    display_unlock();
    return out;
}


// Silent auto-abort: a recording that captured no speech in its first VOICE_SILENCE_MS (an accidental or
// forgotten Voice press). Throws it away — no `voice.end` goes out, so grid-app has nothing to transcribe
// — and restores the UI. Silent on purpose: nothing was said, so there is nothing to report.
static void ui_voice_discard_silent(void)
{
    ESP_LOGI(TAG, "voice: no speech in first %us — auto-discard", VOICE_SILENCE_MS / 1000);
    if (voice_active()) voice_abort();
    display_lock();
    s_voice_routing = false;
    s_voice_route_ms = 0;
    voice_icon_apply(VIC_NONE);
    voice_overlay_set(false);
    update_stop_btn();
    display_unlock();
}

static void voice_start_impl(voice_cmd_t cmd)
{
    if (voice_active()) { ESP_LOGW(TAG, "voice: already active"); return; }
    // Gate on the LINK, which is what voice actually rides (voice.begin → 0x02 PCM frames → voice.end).
    // The panel holds no cloud credential and never talks to one: grid-app hands the audio to
    // `grid stt transcribe`, which authenticates with the session token the CLI already has.
    if (!panel_client_is_connected()) { ESP_LOGW(TAG, "voice: grid-app not connected"); return; }
    const char *pid = ui_get_active_project_id();
    bool route = false;
    if (!pid[0]) {
        // No focused project tile. From the OVERVIEW tile a voice turn is a ROUTE turn: `voice.begin`
        // omits projectId entirely, and grid-app has to work out where the words belong (protocol.md §2).
        display_lock(); bool overview = s_overview_active; display_unlock();
        if (!overview) { ESP_LOGW(TAG, "voice: no active project tile"); return; }
        route = true;
    }
    ESP_LOGI(TAG, "voice start: %s", route ? "ROUTE(overview)" : pid);
    // Interrupt any RUNNING turn first, so the new spoken instruction takes over instead of being queued
    // behind it. Guard on the tile's actual processing state: stopping a project with nothing in flight
    // is a no-op in grid-app, but sending one anyway would put a stop on the wire for every voice press.
    display_lock();
    int aidx = (s_active_idx >= 0 && s_active_idx < s_proj_count) ? s_active_idx : 0;
    bool processing = (!route && s_proj_count > 0 && s_proj[aidx].busy != NULL);   // route has no focused project
    display_unlock();
    if (processing) { ESP_LOGI(TAG, "voice → interrupt the running turn first (%s)", pid); panel_client_stop_project(pid); }
    // Show the mic indicator (red) — it's hidden whenever we're not recording. Clear the active tile's
    // processing row + hide STOP (the mic owns the bottom-center spot while recording).
    display_lock();
    s_voice_start_ms = lv_tick_get();             // arm the normal 10-minute watchdog (busy_dots_tick)
    s_voice_max_ms = 600000u;                     // quota status may shorten this after voice_start reaches backend
    s_voice_routing = route;                       // route (Overview) voice → hold the loading overlay past upload
    s_voice_route_ms = 0;                          // (armed at upload-complete in busy_dots_tick)
    s_voice_cmd = cmd;                            // drives the GOAL/LOOP banner above the waveform
    voice_icon_apply(VIC_MIC);                    // press → mic icon
    voice_overlay_set(true);                      // dark overlay + free all tile content (RAM for the upload)
    lv_timer_create(vic_to_rec_cb, 450, NULL);    // → recording bars after a brief beat
    if (!route && s_proj_count > 0) clear_busy(&s_proj[aidx]);
    update_stop_btn();
    display_unlock();
    // ONE call, where the reference has three. Its two extra entry points existed to vary a WS header
    // (a session id to resume, a per-agent autonomy mode); neither has a counterpart here — grid-app
    // decides which conversation a project's turn goes into, and it is the only thing that could.
    // `route` is simply "no project id", which `voice.begin` expresses by omitting the field.
    voice_start(route ? NULL : pid, cmd);
}

void ui_voice_start(void)      { voice_start_impl(VOICE_CMD_NONE); }   // double-tap / Ask → plain turn
void ui_voice_start_goal(void) { voice_start_impl(VOICE_CMD_GOAL); }   // Goal pill, and touch.c's 2s hold
void ui_voice_start_loop(void) { voice_start_impl(VOICE_CMD_LOOP); }   // Loop pill

void ui_voice_stop(void)
{
    // Hide the recording indicator FIRST and unconditionally: voice_stop() can block
    // (WS stop/destroy, esp. if the socket was mid-connect during a backend restart), and the
    // mic icon must never stay stuck on screen after recording ends.
    // Recording ended → the clip now uploads (audio_client stays active). Swap the mic for a "Sending…"
    // label so the ~15s upload isn't a silent void; busy_dots_tick hides it once the upload completes.
    display_lock();
    if (voice_active()) { voice_icon_apply(VIC_SEND); }   // recording ended → sending spinner (overlay stays up, content stays freed until busy_dots_tick sees the upload finish)
    else                       { s_voice_routing = false; s_voice_route_ms = 0; voice_icon_apply(VIC_NONE); voice_overlay_set(false); }  // nothing to send → restore the UI now
    update_stop_btn();
    display_unlock();
    if (voice_active()) voice_stop();
}

void ui_set_machine_name(const char *name)
{
    display_lock();
    snprintf(s_machine_name, sizeof(s_machine_name), "%s", name && name[0] ? name : "");
    // Both places the name appears: the Overview eyebrow (which names the machine the projects live on)
    // and the band title on a project tile. rebuild_page_dots owns the second one — see the note there
    // for why the band repaint hangs off it.
    if (s_overview_machine_lbl)
        lv_label_set_text(s_overview_machine_lbl, s_machine_name[0] ? s_machine_name : "Machine");
    rebuild_page_dots();
    display_unlock();
}

// Swipe the carousel end to end, `passes` times, so a stutter can be MEASURED instead of described.
//
// The pair to display_draw_stats(): that says how much was repainted, this makes the repainting happen
// on demand and identically every time. A finger cannot do that — swipe speed and length vary per try,
// which is exactly the variance that makes "is it smoother now?" unanswerable.
//
// It is a floor, not the whole cost: an animated scroll_to is cheaper than a drag, because a drag also
// runs the touch driver and LVGL's momentum. A number that gets WORSE here is real; a number that looks
// fine here still has to be confirmed with a finger.
void ui_scroll_benchmark(int passes)
{
    if (passes < 1) passes = 1;
    if (passes > 20) passes = 20;
    // No guard on s_proj_count: with none the ring is still two pages (Overview and the empty page)
    // and scrolling between them is exactly the measurement that isolates the frame from the content.
    for (int p = 0; p < passes; p++) {
        for (int r = 0; r < ring_len(); r++) {
            display_lock();
            carousel_goto(col_for_ring_near(carousel_col(), r), LV_ANIM_ON);
            display_unlock();
            vTaskDelay(pdMS_TO_TICKS(600));
        }
    }
}

// A message that says itself and then gets out of the way.
//
// ui_show_error() loads a screen and stays there, which is right for a link that is down and wrong for a
// voice press that caught no speech: the panel would be stuck on a notice about something that already
// finished. The reference has machine_toast() for exactly this and it went with the Machines page; this
// is that idea on the screen this device does have.
static void notice_expire_cb(lv_timer_t *t)
{
    if (lv_screen_active() == scr_error) lv_screen_load(scr_projects);
    lv_timer_delete(t);
}

void ui_show_notice(const char *title, const char *body)
{
    display_lock();
    ui_show_error(title, body);           // takes the lock again; it is recursive
    lv_timer_create(notice_expire_cb, 6000, NULL);
    display_unlock();
}

// ── FIRMWARE UPDATE ─────────────────────────────────────────────────────────────────────────────────
// The panel is rewriting its own flash and must not look frozen while it does. Built on the CONNECTING
// screen — a spinner and one line — rather than on a screen of its own, because that is what an update
// is here: a wait with a name on it.
//
// The reference builds a whole self-contained progress screen (ui_ota_boot_*) with its own bar, because
// its update happens in a dedicated boot mode where ui_init has not run and there is no other screen to
// borrow. That mode does not exist on this device: the image arrives over the cable that is already
// attached, in the middle of an ordinary session, with every screen already built.

void ui_fw_updating(const char *version)
{
    char step[64];
    snprintf(step, sizeof(step), "Updating to %s\xE2\x80\xA6", version && version[0] ? version : "a new build");
    ui_show_connecting(step);
}

void ui_fw_progress(int pct)
{
    if (pct < 0) pct = 0;
    if (pct > 100) pct = 100;
    display_lock();
    if (conn_lbl) lv_label_set_text_fmt(conn_lbl, "Updating\xE2\x80\xA6 %d%%", pct);
    display_unlock();
}

void ui_fw_verifying(void)  { ui_show_connecting("Checking the update\xE2\x80\xA6"); }
void ui_fw_restarting(void) { ui_show_connecting("Restarting\xE2\x80\xA6"); }

void ui_fw_failed(const char *message)
{
    ui_show_error("Update failed", message && message[0] ? message : "The panel is still on its old firmware.");
}

// Is ANY project mid-turn? The firmware update asks before accepting an offer: rebooting over a running
// turn costs work the panel then has to explain the loss of, and the app re-offers in fifteen seconds.
//
// Reads the MODEL, not the widgets — an off-window project holds no LVGL objects at all but its turn is
// just as real.
bool ui_any_project_busy(void)
{
    display_lock();
    bool busy = false;
    for (int i = 0; i < s_proj_count && !busy; i++) busy = s_proj[i].busy_model;
    display_unlock();
    return busy;
}
