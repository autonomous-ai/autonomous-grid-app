// SQUARE 480x480 LCD. This file is the 720px square board's layout brought down to 480, and the two
// scaling rules below are the whole of the port. They are different rules on purpose:
//
//   PAGE GEOMETRY scales by 0.667 (480/720). Band heights, Y positions, margins, column widths — every
//   number that says "this far down the panel" or "this wide across it". The 720px board spent its
//   extra room on air, and that air is what shrinks.
//
//   TYPE SCALES WITH IT. Every face is the 720px original x0.667 (see scripts/gen_fonts.sh). This was
//   the mistake in the first pass: boxes were scaled and type was not, on the theory that 480 is close
//   enough to the round board's 466 to reuse its faces. But this file holds the 720px LAYOUT, so a
//   41px Overview row ended up holding a 35px line and most screens overflowed.
//
//   FINGER SIZES STILL DO NOT. A row you tap or a chip you hit is sized by a fingertip, which knows
//   nothing about the panel: PICK_ROW_H is 66 on BOTH existing boards for that reason. Scaling those
//   by 0.667 would produce a 44px row nobody can hit reliably.
//
// A square panel still has square corners, so nothing here dodges a bezel the way the round board must.
// Anything geometric is expressed against SCR_W/SCR_H rather than written as a literal.
#define SCR_W        BSP_LCD_H_RES
#define SCR_H        BSP_LCD_V_RES
#define SCR_CX       (SCR_W / 2)
#define SCR_CY       (SCR_H / 2)

#define SCREEN_PAD   19          // 28 @720, 18 @466 — the margin reads the same at every size
#define SAFE_CONTENT_W 400       // 600 @720, 384 @466: a readable centred column
#define SAFE_W       lv_pct(92)  // was 72% to stay inside the curve. Square corners → nearly full width;
                                 // the remaining 8% is ordinary margin, not bezel avoidance.
// One width for EVERY pill row (Settings, the Wifi picker, the brightness slider). The round board gives
// each row a different width — 336 at the top, 427 across the middle, 320 in the picker — so the stack
// follows the circle's chord. A square panel has no chord: rows of differing widths there just look
// misaligned, so they all share this one.
#define SETTINGS_ROW_W  (SCR_W - 2 * SCREEN_PAD)

