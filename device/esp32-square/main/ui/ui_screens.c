static lv_obj_t *make_screen(void)
{
    lv_obj_t *s = lv_obj_create(NULL);
    lv_obj_set_style_bg_color(s, COL_BG, 0);
    lv_obj_set_style_bg_opa(s, LV_OPA_COVER, 0);
    lv_obj_set_style_border_width(s, 0, 0);
    // radius 0, NOT the round board's LV_RADIUS_CIRCLE.
    //
    // On a 466px round panel a full-screen circle is invisible — the glass is already that shape. On a
    // 720px square panel it is very visible indeed: a black disc with the screen's corners showing around
    // it. That is what the "No WiFi found" screen looked like here.
    //
    // It also cost more than looks. A full-screen object with a large corner radius cannot be drawn
    // directly: LVGL renders it through an intermediate clipping LAYER (the same path the brightness
    // slider avoids further down, for the same reason). At 720x720 that is a big allocation and a slow
    // composite on every screen load — which is the ~1s coloured flash seen when entering or cancelling
    // the WiFi setup. Square corners need no layer, so both the disc and the flash go away together.
    lv_obj_set_style_radius(s, 0, 0);
    lv_obj_set_style_pad_all(s, SCREEN_PAD, 0);
    lv_obj_set_flex_flow(s, LV_FLEX_FLOW_COLUMN);
    lv_obj_set_flex_align(s, LV_FLEX_ALIGN_CENTER, LV_FLEX_ALIGN_CENTER, LV_FLEX_ALIGN_CENTER);
    lv_obj_set_style_pad_row(s, 10, 0);
    lv_obj_clear_flag(s, LV_OBJ_FLAG_SCROLLABLE);
    return s;
}

// ---- iOS-style loading spinner: 12 white rounded bars, brightest at the head, fading around, rotating ----
// Each spoke is a rounded-rect with a UNIFORM bg opacity (no line end-caps → no bright dots at the ends);
// oriented radially by a fixed transform_rotation. Only the opacity animates. sin/cos of i*30° (from top).
#define SPIN_SPOKES 12
static const float SPIN_S30[SPIN_SPOKES] = {0,.5f,.866f,1,.866f,.5f,0,-.5f,-.866f,-1,-.866f,-.5f};    // sin(i*30)
static const float SPIN_C30[SPIN_SPOKES] = {1,.866f,.5f,0,-.5f,-.866f,-1,-.866f,-.5f,0,.5f,.866f};     // cos(i*30)
typedef struct { lv_obj_t *spoke[SPIN_SPOKES]; lv_timer_t *timer; int phase; } spinner_t;

static void spinner_tick(lv_timer_t *t)
{
    spinner_t *s = lv_timer_get_user_data(t);
    s->phase = (s->phase + 1) % SPIN_SPOKES;
    for (int i = 0; i < SPIN_SPOKES; i++) {
        int d = (i - s->phase + SPIN_SPOKES) % SPIN_SPOKES;   // 0 = head (brightest)
        lv_opa_t opa = (lv_opa_t)(255 - d * 200 / (SPIN_SPOKES - 1));   // head 255 → tail ~55
        lv_obj_set_style_bg_opa(s->spoke[i], opa, 0);
    }
}

static void spinner_del(lv_event_t *e)
{
    spinner_t *s = lv_event_get_user_data(e);
    if (!s) return;
    if (s->timer) lv_timer_delete(s->timer);
    lv_free(s);
}

// iOS-style spinner sized size×size. Returns the container — hide/show/align it like any object.
static lv_obj_t *make_spinner(lv_obj_t *parent, int size)
{
    lv_obj_t *c = lv_obj_create(parent);
    lv_obj_remove_style_all(c);
    lv_obj_set_size(c, size, size);
    lv_obj_clear_flag(c, LV_OBJ_FLAG_CLICKABLE | LV_OBJ_FLAG_SCROLLABLE);
    spinner_t *s = lv_malloc(sizeof(spinner_t));
    if (!s) return c;
    s->phase = 0;
    float cxy = size / 2.0f, mid_r = size * 0.335f;
    int len = (int)(size * 0.22f); if (len < 4) len = 4;
    int thick = (int)(size * 0.075f); if (thick < 2) thick = 2;
    for (int i = 0; i < SPIN_SPOKES; i++) {
        lv_obj_t *b = lv_obj_create(c);
        lv_obj_remove_style_all(b);
        lv_obj_clear_flag(b, LV_OBJ_FLAG_CLICKABLE | LV_OBJ_FLAG_SCROLLABLE);
        lv_obj_set_size(b, thick, len);
        lv_obj_set_style_radius(b, thick / 2, 0);            // fully-rounded ends
        lv_obj_set_style_bg_color(b, lv_color_white(), 0);
        lv_obj_set_style_bg_opa(b, LV_OPA_COVER, 0);         // set per-frame by spinner_tick
        int cx = (int)(cxy + mid_r * SPIN_S30[i] + 0.5f);    // bar centre on the ring (top = i0, clockwise)
        int cy = (int)(cxy - mid_r * SPIN_C30[i] + 0.5f);
        lv_obj_set_pos(b, cx - thick / 2, cy - len / 2);
        lv_obj_set_style_transform_pivot_x(b, thick / 2, 0); // rotate around the bar's centre
        lv_obj_set_style_transform_pivot_y(b, len / 2, 0);
        lv_obj_set_style_transform_rotation(b, i * 300, 0);  // i*30° → radial orientation
        s->spoke[i] = b;
    }
    s->timer = lv_timer_create(spinner_tick, 70, s);
    spinner_tick(s->timer);   // set the initial fade gradient
    lv_obj_set_user_data(c, s);
    lv_obj_add_event_cb(c, spinner_del, LV_EVENT_DELETE, s);
    return c;
}

