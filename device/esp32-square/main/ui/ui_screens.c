// --- Carousel scroll helpers ---
// `tileview` is now a plain horizontally-scrollable lv_obj (NOT lv_tileview): paging is done with
// LV_SCROLL_SNAP_CENTER + LV_OBJ_FLAG_SCROLL_ONE (exactly what lv_tileview uses internally, so the feel
// is identical), and each tile is positioned at column*width. carousel_goto centers a column;
// carousel_col reads which column is centered from the scroll position.
static int32_t carousel_w(void) { int32_t w = tileview ? lv_obj_get_width(tileview) : 0; return w > 0 ? w : SCR_W; }
static int32_t carousel_h(void) { int32_t h = tileview ? lv_obj_get_height(tileview) : 0; return h > 0 ? h : SCR_H; }
static void carousel_goto(int col, lv_anim_enable_t anim) { if (tileview && col >= 0) lv_obj_scroll_to_x(tileview, col * carousel_w(), anim); }
static int carousel_col(void) { if (!tileview) return 0; int32_t w = carousel_w(); int32_t sx = lv_obj_get_scroll_x(tileview); return w > 0 ? (int)((sx + w / 2) / w) : 0; }
// Invisible 1px child that forces the scroll content width to (agent_count+1)*W, keeping scroll positions
// ABSOLUTE (one column per agent) even though only the ~CONTENT_WINDOW agent tiles around the visible one
// are ever materialized. A far-off agent then costs ZERO LVGL objects → truly unlimited agent count.
static lv_obj_t *s_carousel_spacer;
// Huge virtual scroll range: the carousel is a RING of (project_count + 1) positions (0 = Overview,
// 1..N = project[r-1]) repeated CAROUSEL_M times. Column c maps to ring position `c % (N+1)`. Starting in
// the middle means you never reach an edge, so EVERY swipe (including Overview ↔ last project) is a
// native adjacent slide — no wrap jump, no recenter. M*W must stay under int32 max: 100000*480 = 48M ✓.
#define CAROUSEL_M 100000
// One LEADING fixed tile (Overview) precedes the projects, and NOTHING trails them. Cyclic order is
// overview → project0 → project1 → … → back to overview, so overview is ring 0 and project i lives at
// ring i+RING_LEAD. An EMPTY machine (N==0) keeps 2 positions [overview, No projects] so the carousel
// stays swipeable.
//
// RING_FIXED IS 0, where the reference reserves one trailing slot for its Machines wheel. This panel
// sees exactly one machine — the computer holding the cable — so a page to choose between machines has
// nothing to put on it. RING_FIXED is kept as a named zero rather than deleted because every derivation
// below reads better as "the agents end where the trailing tiles begin" than as an off-by-one.
#define RING_LEAD  1                    // leading fixed tiles (overview) before the projects
#define RING_FIXED 0                    // trailing fixed tiles: none
static void resize_spacer(void) { if (s_carousel_spacer) lv_obj_set_width(s_carousel_spacer, CAROUSEL_M * carousel_w()); }
static int ring_len(void)      { return RING_LEAD + (s_proj_count > 0 ? s_proj_count : 1) + RING_FIXED; }
static int ring_agents_end(void) { return ring_len() - RING_FIXED; }   // first ring AFTER the projects
static int agent_of_ring(int r) { return r - RING_LEAD; }   // ring → project index (valid RING_LEAD..ring_agents_end()-1)
static int ring_of_agent(int i) { return i + RING_LEAD; }   // agent index → ring
static int ring_of_col(int c) { int m = ring_len(); int r = c % m; return r < 0 ? r + m : r; }
// Nearest column to `cc` whose ring position is `r` (for jump/focus/start).
static int col_for_ring_near(int cc, int r) {
    int m = ring_len();
    int fwd = (((r - ring_of_col(cc)) % m) + m) % m;   // 0..m-1 steps forward to reach ring r
    return (fwd <= m - fwd) ? (cc + fwd) : (cc - (m - fwd));
}
// Set the active page from whichever ring position is centered right now (single source of truth).
static void apply_active_from_col(void)
{
    int r = ring_of_col(carousel_col());
    s_overview_active = (r == 0);
    if (r >= RING_LEAD && r < ring_agents_end()) s_active_idx = agent_of_ring(r);   // project ring → index
    // The identity is in the SHARED band now, so it does not arrive with the tile. Every path that changes
    // which page is centred passes through here, which makes this the one place that has to repaint it.
    hdr_agent_paint();
}

