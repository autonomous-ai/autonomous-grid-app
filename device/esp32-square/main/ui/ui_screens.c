// Refresh the overview tile: eyebrow = the selected machine's name; headline = "N agents".
static void rebuild_overview_tile(void)
{
    if (!s_overview_count_lbl) return;
    if (s_remote_offline_view) {
        if (s_overview_spin) { lv_obj_del(s_overview_spin); s_overview_spin = NULL; }
        // "Node offline" has no number, so it takes the TAIL's slot, not the 92px digits face (which has
        // no letters at all — see gen_fonts.py). The count row hides below.
        lv_label_set_text(s_overview_tail_lbl, "Node offline");
        if (s_overview_offline_hint_lbl) lv_obj_clear_flag(s_overview_offline_hint_lbl, LV_OBJ_FLAG_HIDDEN);
        if (s_overview_offline_cmd_lbl) lv_obj_clear_flag(s_overview_offline_cmd_lbl, LV_OBJ_FLAG_HIDDEN);
    } else if (s_overview_loading) {
        // Agents not loaded yet → show a spinner in place of the (unknown) count; never flash "0 agents".
        lv_obj_add_flag(s_overview_count_lbl, LV_OBJ_FLAG_HIDDEN);
        if (!s_overview_spin) {
            s_overview_spin = make_spinner(s_overview_tile, 56);
            // CENTRED in the empty area between the band and the action bar — not left-pinned where the
            // number is about to land. The count is left-aligned because it belongs to a column of
            // left-aligned things (eyebrow above it, agent rows below); while loading, every one of those
            // is hidden, so the spinner has no column to line up with and a 56px dot against the left
            // margin just reads as a stray widget instead of "this page is still loading".
            lv_obj_align(s_overview_spin, LV_ALIGN_TOP_MID, 0, (BAND_H + OV_ACT_Y) / 2 - 28);
        }
        lv_obj_clear_flag(s_overview_spin, LV_OBJ_FLAG_HIDDEN);
    } else {
        if (s_overview_spin) { lv_obj_del(s_overview_spin); s_overview_spin = NULL; }   // stop its timer
        lv_label_set_text_fmt(s_overview_count_lbl, "%d", s_proj_count);
        lv_obj_clear_flag(s_overview_count_lbl, LV_OBJ_FLAG_HIDDEN);
    }
    // The number label carries the whole lockup: hiding it alone would leave a naked "agents" behind.
    set_hidden(s_overview_count_row, s_remote_offline_view || s_overview_loading);
    rebuild_overview_list();
    if (!s_remote_offline_view) {
        if (s_overview_offline_hint_lbl) lv_obj_add_flag(s_overview_offline_hint_lbl, LV_OBJ_FLAG_HIDDEN);
        if (s_overview_offline_cmd_lbl) lv_obj_add_flag(s_overview_offline_cmd_lbl, LV_OBJ_FLAG_HIDDEN);
    }
    if (s_overview_machine_lbl)
        lv_label_set_text(s_overview_machine_lbl, s_machine_name[0] ? s_machine_name : "Machine");
    act_bar_apply();
    overview_working_apply();
}

// Engine -> product mark. Claude is the only monochrome mask in the set (callers recolor it to
// COL_CLAUDE); the rest carry the exact vendor colors from the same assets the web app uses.
static const lv_image_dsc_t *engine_mark_for(const char *engine)
{
    if (!engine || !engine[0])              return NULL;
    if (!strcmp(engine, "claude"))          return &icon_claude;
    if (!strcmp(engine, "codex"))           return &icon_codex;
    if (!strcmp(engine, "cursor"))          return &icon_cursor;
    if (!strcmp(engine, "opencode"))        return &icon_opencode;
    if (!strcmp(engine, "pi"))              return &icon_pi;
    if (!strcmp(engine, "hermes"))          return &icon_hermes;
    if (!strcmp(engine, "commandcode"))     return &icon_commandcode;
    if (!strcmp(engine, "devin"))           return &icon_devin;
    if (!strcmp(engine, "muse"))            return &icon_muse;
    if (!strcmp(engine, "amp"))             return &icon_amp;
    if (!strcmp(engine, "kilo"))            return &icon_kilo;
    if (!strcmp(engine, "grok"))            return &icon_grok;
    return NULL;
}

// Push the current busy set into the two places that show it: the count tail ("agents \xC2\xB7 2 working") and
// the per-row status. Called on every turn start/end, so no timer is needed — the old version rotated a
// gerund on a 1s tick, which is motion the Overview does not need when the ROW already names who is busy.
// Caller holds the lock.
static void overview_working_apply(void)
{
    if (!s_overview_tail_lbl) return;
    int working = 0;
    if (!s_overview_loading && !s_remote_offline_view)
        for (int i = 0; i < s_proj_count; i++) if (s_proj[i].busy_model) working++;
    if (!s_remote_offline_view) {
        if (working > 0) lv_label_set_text_fmt(s_overview_tail_lbl, "projects \xC2\xB7 %d working", working);
        else             lv_label_set_text(s_overview_tail_lbl, "projects");
    }
    for (int r = 0; r < s_ov_row_count; r++) {
        if (!s_ov_rows[r].status) continue;
        int i = s_ov_rows[r].proj;
        set_hidden(s_ov_rows[r].status, !(i >= 0 && i < s_proj_count && s_proj[i].busy_model));
    }
}

// Tap a row → go to that agent's tile. Keyed by ID, not by index: the row survives in LVGL until the next
// rebuild, and the agent list can be reordered by a reload in between.
static void overview_row_tap(lv_event_t *e)
{
    const char *id = (const char *)lv_obj_get_user_data(lv_event_get_target(e));
    if (!id || !id[0]) return;
    ui_tap_cancel();          // this press is spent on the jump — don't let it land again on the tile we open
    ui_focus_project(id);     // takes the lock itself
}
static void overview_row_free(lv_event_t *e) { free(lv_obj_get_user_data(lv_event_get_target(e))); }

// (Re)build the agent rows. WORKING AGENTS FIRST: the whole reason the list exists is "which one", and
// the answer is almost always the one that is running. Only OV_ROWS_MAX fit without scrolling — the count
// above already states the true total, so a truncated list cannot mislead about how many there are.
static void rebuild_overview_list(void)
{
    if (!s_ov_list) return;
    lv_obj_clean(s_ov_list);           // frees the rows (their DELETE cb releases the strdup'd id)
    lv_obj_scroll_to_y(s_ov_list, 0, LV_ANIM_OFF);   // a rebuilt list starts at the top, not where the old one sat
    s_ov_row_count = 0;
    set_hidden(s_ov_list, s_overview_loading || s_remote_offline_view);
    if (s_overview_loading || s_remote_offline_view) return;

    int order[OV_ROWS_MAX]; int n = 0;
    for (int pass = 0; pass < 2 && n < OV_ROWS_MAX; pass++)
        for (int i = 0; i < s_proj_count && n < OV_ROWS_MAX; i++)
            if (s_proj[i].busy_model == (pass == 0)) order[n++] = i;

    for (int k = 0; k < n; k++) {
        int i = order[k];
        lv_obj_t *row = lv_obj_create(s_ov_list);
        lv_obj_remove_style_all(row);
        lv_obj_set_size(row, lv_pct(100), OV_ROW_H);
        lv_obj_set_style_radius(row, 16, 0);
        lv_obj_set_style_bg_color(row, COL_CARD, 0);
        lv_obj_set_style_bg_opa(row, LV_OPA_COVER, 0);
        lv_obj_set_style_bg_color(row, COL_RAISED, LV_STATE_PRESSED);
        lv_obj_set_style_pad_hor(row, 18, 0);
        lv_obj_set_flex_flow(row, LV_FLEX_FLOW_ROW);
        lv_obj_set_flex_align(row, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_CENTER, LV_FLEX_ALIGN_CENTER);
        lv_obj_set_style_pad_column(row, 14, 0);
        lv_obj_add_flag(row, LV_OBJ_FLAG_CLICKABLE);
        lv_obj_clear_flag(row, LV_OBJ_FLAG_SCROLLABLE);
        lv_obj_set_user_data(row, strdup(s_proj[i].id));
        lv_obj_add_event_cb(row, overview_row_tap, LV_EVENT_CLICKED, NULL);
        lv_obj_add_event_cb(row, overview_row_free, LV_EVENT_DELETE, NULL);

        // Engine mark in a neutral raised square. The square is the constant: marks differ in shape and
        // ink from vendor to vendor, and without a box behind them the four rows never line up.
        lv_obj_t *box = lv_obj_create(row);
        lv_obj_remove_style_all(box);
        lv_obj_clear_flag(box, LV_OBJ_FLAG_CLICKABLE | LV_OBJ_FLAG_SCROLLABLE);
        lv_obj_set_size(box, 44, 44);
        lv_obj_set_style_radius(box, 12, 0);
        lv_obj_set_style_bg_color(box, COL_RAISED, 0);
        lv_obj_set_style_bg_opa(box, LV_OPA_COVER, 0);
        const lv_image_dsc_t *src = engine_mark_for(s_proj[i].engine);
        if (src) {
            lv_obj_t *im = lv_image_create(box);
            lv_image_set_src(im, src);
            lv_image_set_inner_align(im, LV_IMAGE_ALIGN_CENTER);
            lv_image_set_pivot(im, (int32_t)src->header.w / 2, (int32_t)src->header.h / 2);
            // 1:1 on purpose. Scaling puts every redraw of this icon on LVGL's software transform path
            // (lv_draw_sw_img transform_and_recolor), which allocates a temp buffer per draw — the exact
            // allocation that returns NULL and hangs the UI when the pool is tight. Six pixels is not
            // worth a per-frame transform, and 20px inside a 44px box is fine.
            lv_obj_set_size(im, 44, 44);
            lv_obj_center(im);
            if (!strcmp(s_proj[i].engine, "claude")) {   // the only monochrome mask in the set
                lv_obj_set_style_image_recolor(im, COL_CLAUDE, 0);
                lv_obj_set_style_image_recolor_opa(im, LV_OPA_COVER, 0);
            }
        }

        lv_obj_t *nm = lv_label_create(row);
        lv_obj_set_style_text_font(nm, &geist_reg_16, 0);
        lv_obj_set_style_text_color(nm, COL_FG, 0);
        lv_label_set_long_mode(nm, LV_LABEL_LONG_DOT);
        lv_obj_set_flex_grow(nm, 1);
        lv_label_set_text(nm, s_proj[i].name);

        // Only a WORKING agent says anything on the right. Four idle timestamps in a column read as one
        // block and pulled the eye away from the single row that was actually live.
        lv_obj_t *st = lv_label_create(row);
        lv_obj_set_style_text_font(st, &geist_reg_13, 0);
        lv_obj_set_style_text_color(st, COL_YELLOW, 0);
        lv_label_set_text(st, "working");
        set_hidden(st, !s_proj[i].busy_model);

        s_ov_rows[s_ov_row_count].row = row;
        s_ov_rows[s_ov_row_count].status = st;
        s_ov_rows[s_ov_row_count].proj = i;
        s_ov_row_count++;
    }

    // Say it when the cap hides agents. The count above states the true total, but a list that simply
    // stops is indistinguishable from a list that has ended — and the remaining agents ARE reachable,
    // by swiping the carousel, which is worth pointing at rather than leaving to be discovered.
    if (s_proj_count > OV_ROWS_MAX) {
        lv_obj_t *more = lv_label_create(s_ov_list);
        lv_obj_set_style_text_font(more, &geist_reg_13, 0);
        lv_obj_set_style_text_color(more, COL_INK_LOW, 0);
        lv_obj_set_style_pad_top(more, 6, 0);
        lv_label_set_text_fmt(more, "+%d more \xC2\xB7 swipe to reach them", s_proj_count - OV_ROWS_MAX);
    }
}

// Dim the two modifiers with the rest of the bar. By COLOUR, never by layer opacity — a style_opa on a
// parent snapshots the whole subtree into a temp layer, which on this UI is a watchdog reset waiting to
// happen. There is no on/off state left to paint: these are buttons now, not switches.
static void act_mod_apply(void)
{
    lv_color_t goal = s_act_ready ? COL_GOAL   : COL_INK_LOW;
    lv_color_t loop = s_act_ready ? COL_ACCENT : COL_INK_LOW;
    lv_color_t text = s_act_ready ? COL_FG     : COL_INK_LOW;
    for (int k = 0; k < 3; k++) {
        if (!s_act_goal_ico[k]) continue;
        lv_obj_set_style_bg_color(s_act_goal_ico[k], goal, 0);
        lv_obj_set_style_border_color(s_act_goal_ico[k], goal, 0);
    }
    if (s_act_loop_ico) lv_obj_set_style_text_color(s_act_loop_ico, loop, 0);
    if (s_act_goal_lbl) lv_obj_set_style_text_color(s_act_goal_lbl, text, 0);
    if (s_act_loop_lbl) lv_obj_set_style_text_color(s_act_loop_lbl, text, 0);
}

// Show/label/enable the one shared action bar for whatever page is centered.
//
// The bar stays VISIBLE but DISABLED during a reconnect rather than disappearing: its position is what
// the thumb learns, and a control that vanishes and returns teaches nothing. It hides only where it
// would be a lie — no page to talk to, or another surface already owns the screen.
//
// Caller holds the display lock (or runs on the LVGL task during ui_init).
static void act_bar_apply(void)
{
    if (!s_act_bar) return;
    // Settings, the question dialog, the reader and the pairing flow are each their OWN lv screen, so this
    // one test excludes all of them; only the Machines tile shares scr_projects and needs naming.
    bool a_page = lv_screen_active() == scr_projects;
    bool overview = a_page && s_overview_active;
    // On Overview the bar routes to whichever agent fits, so it needs the list loaded and non-empty. On an
    // agent tile it talks to THAT agent, so it needs a tile to be there at all (s_proj_count > 0 also rules
    // out the "No agents yet" page, which occupies the same ring slot).
    bool usable = a_page && !s_remote_offline_view && !s_overview_loading && s_proj_count > 0;
    // While recording, the voice overlay owns the whole screen and a tap anywhere stops the turn — a live
    // button under it would fight that.
    set_hidden(s_act_bar, !usable || ui_voice_is_active());
    if (s_act_voice_lbl)
        lv_label_set_text(s_act_voice_lbl, overview ? "Ask any project" : "Voice");   // Overview routes; a tile does not

    s_act_ready = usable && s_connected;
    lv_obj_t *btns[] = { s_act_voice_btn, s_act_goal_btn };
    for (int i = 0; i < 2; i++) {
        if (!btns[i]) continue;
        if (s_act_ready) lv_obj_remove_state(btns[i], LV_STATE_DISABLED);   // state still gates the CLICK
        else             lv_obj_add_state(btns[i], LV_STATE_DISABLED);
    }
    // …but the LOOK is repainted, not faded. See s_act_ready's note: a faded layer costs a full-width
    // per-pixel blend on every refresh; three colour writes cost nothing and read the same.
    if (s_act_voice_btn) {
        lv_obj_set_style_bg_color(s_act_voice_btn, s_act_ready ? lv_color_hex(0x10281a) : lv_color_hex(0x18130d), 0);
        lv_obj_set_style_border_color(s_act_voice_btn, s_act_ready ? lv_color_hex(0x24512f) : COL_HAIRLINE, 0);
    }
    if (s_act_voice_lbl) lv_obj_set_style_text_color(s_act_voice_lbl, s_act_ready ? COL_VOICE : COL_INK_LOW, 0);
    if (s_act_voice_mic) lv_obj_set_style_image_recolor(s_act_voice_mic, s_act_ready ? COL_VOICE : COL_INK_LOW, 0);
    act_mod_apply();
}

// The primary action, on BOTH page kinds. No branch here on purpose: voice_start_impl already resolves
// "which agent" from the focused tile and falls back to a routed turn on Overview, so duplicating that
// decision at the button would be a second place for the two to disagree.
static void act_voice_tap(lv_event_t *e)
{
    (void)e;
    if (!s_connected || s_overview_loading || s_remote_offline_view || s_proj_count <= 0 || voice_active()) return;
    ESP_LOGI(TAG, "action bar: ask (overview=%d)", (int)s_overview_active);
    ui_voice_start();
}

// Goal and Loop START a recording; they do not arm a mode. That REVERSES the switch this bar used to
// carry, and the trade deserves writing down rather than being discovered later: the switch showed its
// state while you were not using it and cost two gestures (arm, then speak), whereas three buttons cost
// one gesture and carry no state to forget — but they also cannot answer "is goal still on?", because
// there is no longer anything to be on. Each one changes only what the backend puts in front of the
// transcript: nothing, /goal, or /loop.
static void act_goal_tap(lv_event_t *e)
{
    (void)e;
    if (!s_act_ready || voice_active()) return;
    ESP_LOGI(TAG, "action bar: goal (overview=%d)", (int)s_overview_active);
    ui_voice_start_goal();
}

static void act_loop_tap(lv_event_t *e)
{
    (void)e;
    if (!s_act_ready || voice_active()) return;
    ESP_LOGI(TAG, "action bar: loop (overview=%d)", (int)s_overview_active);
    ui_voice_start_loop();
}

// touch.c calls this on press-down before its screen-wide gesture recognizers. Capturing a gesture that
// starts on either action prevents a long hold on Voice becoming the global Goal gesture, while LVGL still
// receives the original pointer stream and dispatches the normal button click.
bool ui_action_hit(uint16_t x, uint16_t y)
{
    // The status-band icons FIRST, and on any screen: they sit inside the notification pull-down zone, so
    // without this the drawer gesture swallows every press and neither icon can ever be tapped. Checked
    // before the voice guard below because the bell and gear are the two always-on controls.
    if (!display_is_asleep()) {
        lv_point_t bp = { .x = x, .y = y };
        if (s_band_noti && lv_obj_hit_test(s_band_noti, &bp)) return true;
        // The Model and Effort chips joined them in this band when the identity row moved up, and they
        // need the same claim for the same reason. Before the merge they sat at y=122, below the drawer's
        // zone entirely, so the zone never saw them; now being in the band is the only thing between them
        // and a pull-down that swallows every press.
        // Scoped to the projects screen with no drawer over it. lv_obj_hit_test() knows nothing about
        // which screen is loaded or what is on top of it, and s_hdr_ctl's HIDDEN flag is only refreshed by
        // hdr_agent_paint() — so without this the chips' rectangle would keep claiming presses on Settings,
        // on the pickers, and through the notification drawer that covers this very band.
        if (lv_screen_active() == scr_projects && !ui_notif_is_open()
            && s_hdr_ctl && !lv_obj_has_flag(s_hdr_ctl, LV_OBJ_FLAG_HIDDEN)) {
            if (s_hdr_model && !lv_obj_has_flag(s_hdr_model, LV_OBJ_FLAG_HIDDEN)
                && lv_obj_hit_test(s_hdr_model, &bp)) return true;
            if (s_hdr_effort && !lv_obj_has_flag(s_hdr_effort, LV_OBJ_FLAG_HIDDEN)
                && lv_obj_hit_test(s_hdr_effort, &bp)) return true;
        }
    }
    // During a voice turn the buttons are hidden under the overlay and must NOT capture the gesture — else
    // touch.c suppresses tap-to-stop for the whole press, so a tap to stop the voice does nothing. Let the
    // tap flow to tap-to-stop; the clickable overlay blocks the LVGL button click anyway.
    if (voice_active()) return false;
    if (display_is_asleep() || lv_screen_active() != scr_projects ||
        !s_act_bar || lv_obj_has_flag(s_act_bar, LV_OBJ_FLAG_HIDDEN)) return false;
    // No s_overview_active test: the bar is on every agent tile now, and act_bar_apply() has already
    // hidden it wherever it does not belong — asking twice would just let the two answers drift.
    lv_point_t p = { .x = x, .y = y };
    if ((s_act_voice_btn && lv_obj_hit_test(s_act_voice_btn, &p)) ||
        (s_act_goal_btn  && lv_obj_hit_test(s_act_goal_btn,  &p)) ||
        (s_act_loop_btn  && lv_obj_hit_test(s_act_loop_btn,  &p))) return true;
    // The Overview agent rows are controls too, and they need this for a REASON that is easy to miss:
    // without it the same press both fires the row (jump to that agent) AND lands as the screen's deferred
    // tap, which the freshly-focused agent tile then reads as "open the detail reader". You tapped once and
    // travelled two screens. Claiming the press here withholds that deferred tap, exactly as it does for
    // the action bar, and also stops a long hold on a row from firing the global Goal gesture.
    if (s_overview_active && s_ov_list && !lv_obj_has_flag(s_ov_list, LV_OBJ_FLAG_HIDDEN))
        for (int r = 0; r < s_ov_row_count; r++)
            if (s_ov_rows[r].row && lv_obj_hit_test(s_ov_rows[r].row, &p)) return true;
    return false;
}

