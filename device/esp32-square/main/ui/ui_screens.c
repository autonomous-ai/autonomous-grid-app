static void str_tolower(char *s) { for (; *s; ++s) *s = (char)tolower((unsigned char)*s); }

// Percent-decode src[0..len) into out (the session id in a runtime-v1 profile is URL-encoded).
static void pct_decode(const char *src, size_t len, char *out, size_t cap)
{
    size_t o = 0;
    for (size_t i = 0; i < len && o + 1 < cap; i++) {
        if (src[i] == '%' && i + 2 < len && isxdigit((unsigned char)src[i + 1]) && isxdigit((unsigned char)src[i + 2])) {
            char h[3] = { src[i + 1], src[i + 2], 0 };
            out[o++] = (char)strtol(h, NULL, 16);
            i += 2;
        } else {
            out[o++] = src[i];
        }
    }
    out[o] = '\0';
}

// Parse "runtime-v1:<sid>:<engine>:<model>@<effort>". sid AND model are percent-decoded — the producer
// (web encodeRuntimeProfile) runs encodeURIComponent over both. This used to decode only the sid, on the
// stated assumption that a model alias is "never %xx". That held by luck for years: every alias so far
// (opus, sonnet, gpt-5.6-sol) is entirely unreserved characters, so the encode was a no-op. Kilo's id is
// "Kilo/kilo", the first with a '/', and it reached the panel as "Kilo%2Fkilo".
// Effort really is raw — the producer interpolates it unencoded and it is constrained to [a-z0-9_-].
// Decoding BOTH sides keeps catalog comparisons consistent, and the picker still round-trips the id
// verbatim (s_pick_ids copies cat[].id, never this output). Any out ptr may be NULL.
// Returns true only for a well-formed profile.
static bool parse_runtime_profile(const char *id, char *sid, size_t scap,
                                  char *model, size_t mcap, char *effort, size_t ecap)
{
    if (sid && scap) sid[0] = '\0';
    if (model && mcap) model[0] = '\0';
    if (effort && ecap) effort[0] = '\0';
    if (!id || strncmp(id, "runtime-v1:", 11) != 0) return false;
    const char *s  = id + 11;
    const char *c1 = strchr(s, ':');         if (!c1) return false;        // end of sid
    if (sid && scap) pct_decode(s, (size_t)(c1 - s), sid, scap);
    const char *c2 = strchr(c1 + 1, ':');    if (!c2) return false;        // end of engine
    const char *m  = c2 + 1;
    const char *at = strrchr(m, '@');        if (!at || at <= m) return false;
    if (model && mcap) pct_decode(m, (size_t)(at - m), model, mcap);
    if (effort && ecap) { snprintf(effort, ecap, "%s", at + 1); str_tolower(effort); }
    return (!model || model[0]) && (!effort || effort[0]);
}

// "xhigh"→"XHigh", "auto"→"Auto", else Titlecase (mirrors web formatEffortLabel).
static void format_effort_label(const char *effort, char *out, size_t cap)
{
    if (!effort || !effort[0] || !strcasecmp(effort, "auto")) { snprintf(out, cap, "Auto"); return; }
    if (!strcasecmp(effort, "xhigh")) { snprintf(out, cap, "XHigh"); return; }
    snprintf(out, cap, "%c%s", (char)toupper((unsigned char)effort[0]), effort + 1);
}

// Format a raw model alias for display. Known Claude aliases → Titlecase ("opus"→"Opus"); other slugs are
// split on -/_ into space-joined title-cased words, with a standalone "gpt" word upper-cased ("gpt-5.6-sol"
// → "GPT 5.6 Sol"). Mirrors web formatModelLabel closely enough for the chip + rows.
static void format_model_label(const char *alias, char *out, size_t cap)
{
    if (!alias || !alias[0]) { snprintf(out, cap, "Auto"); return; }
    static const char *known[] = { "default", "best", "fable", "opus", "sonnet", "haiku" };
    for (size_t k = 0; k < sizeof(known) / sizeof(known[0]); k++) {
        size_t klen = strlen(known[k]);
        if (!strncasecmp(alias, known[k], klen) && (alias[klen] == '\0' || !strcasecmp(alias + klen, "[1m]"))) {
            snprintf(out, cap, "%c%s", (char)toupper((unsigned char)alias[0]), alias + 1);
            return;
        }
    }
    size_t o = 0;
    const char *c = alias;
    while (*c && o + 1 < cap) {
        const char *w = c;
        while (*c && *c != '-' && *c != '_') c++;
        size_t wl = (size_t)(c - w);
        if (o && o + 1 < cap) out[o++] = ' ';
        if (wl == 3 && !strncasecmp(w, "gpt", 3)) {
            if (o + 3 < cap) { out[o++] = 'G'; out[o++] = 'P'; out[o++] = 'T'; }
        } else {
            for (size_t k = 0; k < wl && o + 1 < cap; k++) {
                char ch = w[k];
                if (k == 0 && islower((unsigned char)ch)) ch = (char)toupper((unsigned char)ch);
                out[o++] = ch;
            }
        }
        while (*c == '-' || *c == '_') c++;
    }
    out[o] = '\0';
}

// Re-derive model_alias / effort / model_label from p->selected_model. Unparseable/empty → Auto, no effort.
// TWO shapes accepted, where the reference accepts one.
//
// The reference's backend always sends the opaque runtime-v1 profile above, so anything else is a bug
// there and "Auto" is the right answer. grid-app sends the model's plain name — "opus", "gpt-5.6-sol" —
// because that is all it has: a project runs on a model, and there is no per-agent effort setting behind
// it to encode. Falling through to "Auto" for that would print Auto on a panel showing a project that is
// demonstrably running on something.
//
// So: parse the profile when it is one, and otherwise treat the whole string as the model name. Effort
// stays empty, which is what hides the Effort chip.
static void parse_and_store(proj_t *p)
{
    if (parse_runtime_profile(p->selected_model, NULL, 0, p->model_alias, sizeof(p->model_alias),
                              p->effort, sizeof(p->effort))) {
        format_model_label(p->model_alias, p->model_label, sizeof(p->model_label));
        return;
    }
    p->effort[0] = '\0';
    if (p->selected_model[0]) {
        snprintf(p->model_alias, sizeof(p->model_alias), "%s", p->selected_model);
        format_model_label(p->model_alias, p->model_label, sizeof(p->model_label));
    } else {
        p->model_alias[0] = '\0';
        snprintf(p->model_label, sizeof(p->model_label), "Auto");
    }
}

// A small glass-pill chip for the per-agent controls row (Model / Effort). Clickable → opens a picker.
static lv_obj_t *ctl_chip(lv_obj_t *parent, lv_event_cb_t cb)
{
    lv_obj_t *c = lv_label_create(parent);
    lv_obj_set_style_text_font(c, CTL_CHIP_FONT, 0);
    // The chips only ever show on an agent tile, so they wear the page unconditionally. They keep their
    // HUE — blue for a set model, green for a set effort — because that is what says which chip is which
    // and whether a value is set; draining it to ink would cost information the warm palette never had.
    lv_obj_set_style_text_color(c, COL_INK_MID, 0);
    lv_obj_set_style_bg_color(c, lv_color_hex(0x241f18), 0);
    lv_obj_set_style_bg_opa(c, LV_OPA_70, 0);
    lv_obj_set_style_radius(c, LV_RADIUS_CIRCLE, 0);
    lv_obj_set_style_border_width(c, 1, 0);
    lv_obj_set_style_border_color(c, COL_HAIRLINE, 0);
    // The chips sit BESIDE the name and were the loudest thing in the band — a saturated blue and green
    // outline each. They keep their hue, because it is what says which chip is which and whether a value
    // is set, but at 60% the line stops competing with the answer below it.
    lv_obj_set_style_border_opa(c, LV_OPA_60, 0);
    lv_obj_set_style_pad_hor(c, CTL_CHIP_PAD_H, 0);
    lv_obj_set_style_pad_ver(c, CTL_CHIP_PAD_V, 0);
    // The reference makes these tappable and `cb` opens its Model / Effort picker. Both call sites pass
    // NULL here, and the parameter stays so the shape of the function still says what a chip could be.
    if (cb) {
        lv_obj_add_flag(c, LV_OBJ_FLAG_CLICKABLE);
        lv_obj_set_ext_click_area(c, 12);   // forgiving tap target
        lv_obj_add_event_cb(c, cb, LV_EVENT_CLICKED, NULL);
    }
    return c;
}

// Paint the Model chip from p->model_label (empty alias = "Auto", muted).
// Long names still need clipping — Command Code and Devin carry names like "Deepseek V4 Flash" or
// "Nemotron 3 Ultra 550b A55b", which no chip will ever hold — but the reason is now simply row width,
// not the round board's chord at this Y. Clip hard, no ellipsis (it only ate a glyph's worth of the room
// it was meant to save). Counted in CODEPOINTS, not bytes, so a multi-byte name is never cut mid-character
// into a garbage glyph. The picker still lists full names.
//
// Raised from the round board's 11/6: the pill grew with the panel but the font grew too, so the gain is
// the width difference, not the full 1.55x. Verify on hardware with a long Command Code model name.
#define MODEL_CHIP_MAX_CHARS  14
#define EFFORT_CHIP_MAX_CHARS 8
static void chip_clip(const char *src, char *out, size_t cap, size_t max_glyphs)
{
    if (!out || cap == 0) return;
    out[0] = '\0';
    if (!src) return;
    size_t glyphs = 0, i = 0;
    while (src[i] && glyphs < max_glyphs) {
        size_t len = 1;
        unsigned char c = (unsigned char)src[i];
        if      ((c & 0xE0) == 0xC0) len = 2;
        else if ((c & 0xF0) == 0xE0) len = 3;
        else if ((c & 0xF8) == 0xF0) len = 4;
        for (size_t k = 1; k < len; k++) if (!src[i + k]) { len = k; break; }   // truncated input
        i += len;
        glyphs++;
    }
    size_t keep = i < cap - 1 ? i : cap - 1;
    memcpy(out, src, keep);
    out[keep] = '\0';
}

// The chips are ONE pair of objects in the header band now, not a pair per tile, so every paint below is
// a no-op unless `p` is the agent currently on screen. Callers still pass whichever project changed — a
// model update can arrive for an agent three swipes away — and hdr_agent_paint() repaints on the swipe,
// so an off-screen change lands the moment that agent comes back into view.
static bool proj_is_active(const proj_t *p)
{
    return p && s_active_idx >= 0 && s_active_idx < s_proj_count && &s_proj[s_active_idx] == p;
}

static void model_chip_paint(proj_t *p)
{
    if (!s_hdr_model || !proj_is_active(p)) return;
    bool has = p->model_alias[0] != '\0';
    char label[48];
    chip_clip(p->model_label, label, sizeof(label), MODEL_CHIP_MAX_CHARS);
    lv_label_set_text(s_hdr_model, has ? label : "Auto");
    lv_obj_set_style_text_color(s_hdr_model, has ? COL_INK_MID : COL_INK_LOW, 0);
    lv_obj_set_style_border_color(s_hdr_model, has ? COL_ACCENT : COL_HAIRLINE, 0);
}

// Paint the Effort chip. Shown whenever a model is known (so the user can always open the effort picker,
// even from "Auto"); hidden only when there is no model yet. Green when an explicit effort is set, muted
// "Auto" otherwise. Whether a model actually has explicit effort levels is decided by the effort picker
// (which shows nothing + bounces back for auto-only models).
static void effort_chip_paint(proj_t *p)
{
    if (!s_hdr_effort || !proj_is_active(p)) return;
    bool has_eff = p->effort[0] && strcasecmp(p->effort, "auto") != 0;
    // HIDDEN unless there is a real effort to show, where the reference shows a muted "Auto" whenever a
    // model is set. That reads as a control on its board, because tapping it opens a picker. Here it is
    // display-only and grid-app has no effort field at all, so an "Auto" chip would sit in the band for
    // the device's whole life saying nothing and never changing — a permanent label pretending to be a
    // value. The model chip beside it keeps its "Auto", because that one does vary.
    if (!has_eff) {
        lv_obj_add_flag(s_hdr_effort, LV_OBJ_FLAG_HIDDEN);
        return;
    }
    lv_obj_clear_flag(s_hdr_effort, LV_OBJ_FLAG_HIDDEN);
    char lbl[16], clipped[16];
    format_effort_label(p->effort, lbl, sizeof(lbl));   // "Auto" when empty/auto
    chip_clip(lbl, clipped, sizeof(clipped), EFFORT_CHIP_MAX_CHARS);
    lv_label_set_text(s_hdr_effort, clipped);
    lv_obj_set_style_text_color(s_hdr_effort, has_eff ? COL_GREEN : COL_INK_LOW, 0);
    lv_obj_set_style_border_color(s_hdr_effort, has_eff ? COL_GREEN : COL_HAIRLINE, 0);
}

