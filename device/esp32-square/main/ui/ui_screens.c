void ui_voice_routed(bool auto_sent, bool need_new, const char *route_id, const char *agent_id,
                     const char *agent_name, double confidence)
{
    ESP_LOGI(TAG, "voice_routed: auto=%d need_new=%d agent='%s' name='%s' conf=%.2f",
             auto_sent, need_new, agent_id ? agent_id : "", agent_name ? agent_name : "", confidence);
    // Router answered → the routing wait is over. Drop the "Sending…" loading overlay so the UI is
    // interactive again (and busy_dots_tick stops holding it).
    display_lock();
    s_voice_routing = false; s_voice_route_ms = 0;
    voice_icon_apply(VIC_NONE);
    voice_overlay_set(false);
    display_unlock();
    // No agent fit (router wants a new agent) — MVP: stay on Overview. (Create-agent flow is a later phase.)
    if (need_new || !agent_id || !agent_id[0]) return;
    // Switch the carousel to the picked agent so the user sees it working.
    ui_focus_project(agent_id);
    // High-confidence: the backend already dispatched — nothing more to do. Otherwise the transcript is held
    // for confirmation; MVP auto-confirms so the turn still runs (a manual confirm card is a later refinement).
    if (!auto_sent && route_id && route_id[0]) panel_client_voice_confirm(route_id, agent_id);
}

