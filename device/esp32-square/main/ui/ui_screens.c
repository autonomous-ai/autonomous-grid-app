// Clip a project name to at most 15 UTF-8 chars (whole codepoints), appending "…" when longer.
//
// Deliberately the SAME 15 as the round board, even though this panel has room for more. The adapter
// clips agent names to 15 codepoints / 39 bytes before they are ever sent to a device
// (DEVICE_AGENT_NAME_MAX_* in the harness CLI (public repo)/src/backendSocket.ts), so a larger number here buys
// nothing — the longer name never arrives. Owner's call (2026-08-03) is to keep both boards showing the
// same thing rather than raise the shared limit. If that limit ever moves, move it there first.
static void name_clip(const char *in, char *out, size_t cap)
{
    const int MAX_CP = 15;
    const unsigned char *p = (const unsigned char *)in;
    size_t o = 0; int cp = 0;
    while (*p && cp < MAX_CP) {
        int len = (*p < 0x80) ? 1 : ((*p & 0xE0) == 0xC0) ? 2 : ((*p & 0xF0) == 0xE0) ? 3 : ((*p & 0xF8) == 0xF0) ? 4 : 1;
        if (o + (size_t)len + 4 > cap) break;               // leave room for "…" + NUL
        for (int k = 0; k < len && p[k]; k++) out[o++] = (char)p[k];
        p += len; cp++;
    }
    if (*p && o + 4 <= cap) { out[o++] = (char)0xE2; out[o++] = (char)0x80; out[o++] = (char)0xA6; }  // …
    out[o] = '\0';
}

void ui_project_set_name(const char *project_id, const char *name)
{
    if (!project_id || !name) return;
    display_lock();
    int i = find_proj(project_id);
    if (i < 0) i = add_proj(project_id);
    if (i >= 0) {
        char filtered[80];
        utf8_filter(name, filtered, sizeof(filtered));   // drop glyphs the font can't render (emoji/CJK) → no tofu box
        char clipped[80];
        name_clip(filtered, clipped, sizeof(clipped));
        // A new agent is created BEFORE its name arrives: add_proj() builds the Overview row from a model
        // whose name and engine are still empty, and nothing rebuilt that row when they turned up. The row
        // stayed blank until some unrelated event happened to rebuild the tile — which is why it only
        // appeared "after a reload".
        //
        // Gated on an actual CHANGE, not on being called: refresh_projects() calls this for every agent
        // every 60s, and rebuilding the whole list on each of those would tear the Overview down and build
        // it again once a minute for nothing.
        bool changed = strcmp(s_proj[i].name, clipped) != 0;
        snprintf(s_proj[i].name, sizeof s_proj[i].name, "%s", clipped);   // MODEL: source of truth
        hdr_agent_paint();   // VIEW mirrors model — a no-op unless this agent is the one on screen
        if (changed) rebuild_overview_tile();   // the Overview row shows the name too
    }
    display_unlock();
}

