// ---- lazy content windowing ----
// Only the active tile ± CONTENT_WINDOW keep a materialized CONTENT subtree (body/list/card/busy/…);
// every other project keeps just its thin shell (tile/hdr/dot/name). This bounds the LVGL 64KB pool
// regardless of how many projects exist. The per-project model (m_preview/m_full/m_col/busy_model)
// lets an off-window tile be rebuilt on entry and lets live events (keyed by id) update state without
// touching LVGL until the tile is on-screen.
#define CONTENT_WINDOW 1

// Duplicate into PSRAM so project/event strings never crowd the internal heap.
// Returns NULL for empty input or PSRAM OOM; callers retain the previous model on OOM.
static char *dup_str(const char *s)
{
    if (!s || !s[0]) return NULL;
    return ram_psram_strdup(s, "ui_event_text");
}

// Build the single event-card label into p->list (shared by ui_project_emit's live path and by
// materialize_content). `full` may be NULL (model had only a preview) — the reader then shows preview.
static void render_event_card(proj_t *p, const char *preview, const char *full, lv_color_t col)
{
    if (!p->list || !preview) return;
    if (p->empty) { lv_obj_delete(p->empty); p->empty = NULL; }
    // With no real recap field, `preview` is just the first PREVIEW_BYTES of `full` — a headline set from
    // the body's own opening sentence is not a headline, it is the same words twice. Then there is only
    // a story.
    bool headlined = p->m_has_recap && full && full[0];

    // ONE box, holding the whole article. The recap had its own bare-panel zone above this for exactly
    // one iteration; two surfaces claimed these were two things, and they are not — the recap is the
    // answer in a sentence and the body is the same answer at length. So the split is typographic now,
    // and the box is the only thing left on the panel between the header and the action bar.
    // NO card. There was one for exactly two iterations, and MEASURING it is what ended it: COL_CARD
    // against COL_BG is 1.09:1 — a surface you cannot see. It was not separating anything; it was
    // spending 52px of the reading column and 44px of the height on a frame nobody could make out.
    //
    // A page of a book has no card either. The text sits on the paper and the MARGIN holds it, which the
    // tile already provides (SETTINGS_ROW_W leaves SCREEN_PAD either side). So this object stays for the
    // one thing it actually does: be what scrolls.
    // The text column, as an ABSOLUTE width — see docs/ui.md, "A wrapping label must never take its
    // width from a percentage". The reference sets both labels below to lv_pct(100) inside this very
    // box, which is AUTO-scrollbar, and that is a feedback loop: the scrollbar appears, the content
    // width shrinks, the wrapped label re-wraps, its height changes, whether a scrollbar is needed
    // changes. Every pass re-measures every glyph in Geist. On the glass it reads as the tile
    // flickering and the swipe stuttering — which is the report this whole port started from.
    //
    // Derived, not typed: the box is the full row less its own right pad, so the number cannot drift
    // out of step with the padding above it.
#define WELL_TEXT_W (SETTINGS_ROW_W - 14)
    p->sum_box = lv_obj_create(p->list);
    lv_obj_remove_style_all(p->sum_box);
    lv_obj_set_width(p->sum_box, lv_pct(100));
    lv_obj_set_flex_grow(p->sum_box, 1);           // the whole well
    lv_obj_set_style_bg_opa(p->sum_box, LV_OPA_TRANSP, 0);
    lv_obj_set_style_pad_right(p->sum_box, 14, 0); // clear of the scrollbar; the left edge IS the margin
    lv_obj_set_style_pad_ver(p->sum_box, 4, 0);
    // Column flex, because the headline / rule / story stack and the box scrolls PAST all three — a
    // headline that scrolls away with its story is what makes it a headline rather than a label, and is
    // the read that was chosen over pinning it in a fixed cap.
    lv_obj_set_flex_flow(p->sum_box, LV_FLEX_FLOW_COLUMN);
    lv_obj_set_flex_align(p->sum_box, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_START);
    lv_obj_set_style_pad_row(p->sum_box, 0, 0);
    lv_obj_add_flag(p->sum_box, LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_set_scroll_dir(p->sum_box, LV_DIR_VER);
    // The scrollbar is the ONLY thing saying there is more below, now that the "tap to read" hint and the
    // screen it pointed at are both gone. AUTO, not ON: with MODE_ON LVGL draws the rail full-height even
    // when the content fits, so every short answer would claim there was more. AUTO draws it exactly when
    // there IS overflow, and unlike MODE_ACTIVE it does not fade out after the drag.
    lv_obj_set_scrollbar_mode(p->sum_box, LV_SCROLLBAR_MODE_AUTO);
    lv_obj_set_style_bg_color(p->sum_box, COL_INK_LOW, LV_PART_SCROLLBAR);
    lv_obj_set_style_bg_opa(p->sum_box, LV_OPA_COVER, LV_PART_SCROLLBAR);
    lv_obj_set_style_width(p->sum_box, 5, LV_PART_SCROLLBAR);
    lv_obj_set_style_radius(p->sum_box, 3, LV_PART_SCROLLBAR);
    // remove_style_all() above wiped the theme's scrollbar inset, which would put the rail hard against
    // the 22px rounded corner and over the text column.
    lv_obj_set_style_pad_right(p->sum_box, 6, LV_PART_SCROLLBAR);
    lv_obj_set_style_pad_ver(p->sum_box, 10, LV_PART_SCROLLBAR);

    if (headlined) {
        // THE HEADLINE. Medium, not bold — Roboto Condensed on this board tops out at Medium, so 500
        // against the story's 400 is the entire weight budget. The SIZE step is deliberately small too
        // (38 against 35): print would set a headline at twice the body, but a recap runs a full
        // sentence, and at 2x it takes five lines and buries the story it introduces.
        p->recap_lbl = lv_label_create(p->sum_box);
        lv_label_set_text(p->recap_lbl, preview);
        lv_label_set_long_mode(p->recap_lbl, LV_LABEL_LONG_WRAP);
        lv_obj_set_width(p->recap_lbl, WELL_TEXT_W);   // absolute — see WELL_TEXT_W above
        // Same FAMILY as the story, not the UI's sans. A sans headline over a serif body is the shape of
        // a news site; a page of a book sets both in the one face, and the box is meant to read as a page.
        lv_obj_set_style_text_font(p->recap_lbl, &geist_med_25, 0);
        // INK_MID, not FG. FG on this ground measures 11.68:1 — inside the band the dark-mode literature
        // recommends, and still too hot on a backlit IPS at the brightness this panel actually runs at.
        // The giveaway was that "No activity yet" at 3.44:1 read as EASIER than the article: the dimmest
        // thing on the tile was the most comfortable one on it. 7.07:1 is the headline's share of that.
        lv_obj_set_style_text_color(p->recap_lbl, lv_color_eq(col, COL_FG) ? COL_INK_MID : col, 0);
        lv_obj_set_style_text_align(p->recap_lbl, LV_TEXT_ALIGN_LEFT, 0);
        lv_obj_set_style_text_line_space(p->recap_lbl, 4, 0);

        // And the RULE, which is what actually separates them. It costs one pixel and does the work the
        // three type sizes this board cannot spend would have done.
        lv_obj_t *rule = lv_obj_create(p->sum_box);
        lv_obj_remove_style_all(rule);
        lv_obj_set_width(rule, lv_pct(100));
        lv_obj_set_height(rule, 1);
        lv_obj_set_style_bg_color(rule, COL_HAIRLINE, 0);
        lv_obj_set_style_bg_opa(rule, LV_OPA_COVER, 0);
        lv_obj_set_style_margin_ver(rule, 18, 0);
        lv_obj_clear_flag(rule, LV_OBJ_FLAG_CLICKABLE | LV_OBJ_FLAG_SCROLLABLE);
    }

    // THE STORY. `full`, not `preview`, in both branches: preview is full clipped to PREVIEW_BYTES with
    // an ellipsis — fine back when a tap opened a reader on the rest, and unreadable now that this box IS
    // the reader. The box scrolls, so there is no reason to feed it the teaser.
    lv_obj_t *l = lv_label_create(p->sum_box);
    lv_label_set_text(l, (full && full[0]) ? full : preview);
    lv_label_set_long_mode(l, LV_LABEL_LONG_WRAP);
    lv_obj_set_width(l, WELL_TEXT_W);   // absolute — see WELL_TEXT_W above
    // SERIF, and at FULL page ink rather than a dimmed grey. Dimming the body is right when it is a
    // teaser under a headline you are meant to read first; it is wrong the moment the body is the thing
    // you sit and read, which is what this box became. The headline still wins on size and weight and
    // has a rule under it — that is enough of a ladder without taxing the legibility of the prose.
    lv_obj_set_style_text_font(l, &geist_reg_24, 0);
    // MUTED — 5.00:1. A step under the headline, still clear of WCAG AA's 4.5:1 for body text, and less
    // than half the light per glyph FG was emitting. An event carrying its OWN colour (an error's red)
    // keeps it: that colour is information, and dimming it would be dimming the warning.
    lv_obj_set_style_text_color(l, lv_color_eq(col, COL_FG) ? COL_MUTED : col, 0);
    lv_obj_set_style_text_align(l, LV_TEXT_ALIGN_LEFT, 0);
    // 1.75, which is what a Kindle actually sets — not the 1.50 I had, which came from generic
    // screen-reading guidance rather than from the thing being imitated. geist_reg_24 reports line_height
    // 49, so +10 lands on 59px = 1.74x. Re-derive if the face or size moves: line_space = round(size *
    // 1.75) - line_height.
    //
    // It costs a line of the well and is worth it: loose leading is most of why a page of a book does not
    // feel like a wall of text, and it matters MORE now that the card is gone and the column runs the
    // full 664px — long lines need the extra leading to keep the eye from dropping to the wrong one.
    lv_obj_set_style_text_line_space(l, 10, 0);
    // Ragged right, deliberately. LVGL neither justifies nor hyphenates, and justification without
    // hyphenation opens rivers of white space down the column — worse than an uneven right edge.

}

// Build the Figma "working" status into p->body from the model. A centred block: a green "<verb> <elapsed>"
// line + a grey teaser (last recap). No spinning sparkle — the green LED ring is the loading indicator now.
// Also recentres the whole tile ([name][busy]) vertically for this state (clear_busy restores the recap layout).
static void render_busy_row(proj_t *p)
{
    if (!p->body || p->busy) return;
    // The tile is NOT relaid out here. The round board re-centres the whole tile when a turn starts;
    // doing that re-enables flex on a tile whose bands are pinned at fixed Y and threw the entire working
    // screen out of position. The frame staying put across states is the point of banding it.
    p->busy = lv_obj_create(p->body);
    lv_obj_remove_style_all(p->busy);
    lv_obj_clear_flag(p->busy, LV_OBJ_FLAG_CLICKABLE | LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_set_width(p->busy, lv_pct(100));
    lv_obj_set_height(p->busy, LV_SIZE_CONTENT);
    lv_obj_set_flex_flow(p->busy, LV_FLEX_FLOW_COLUMN);
    // CENTRED, unlike the recap card's prose. A finished answer is read line by line and wants a straight
    // left edge; a live turn is a one- or two-line status readout, and centring keeps the eye in one place
    // while the words underneath keep changing.
    lv_obj_set_flex_align(p->busy, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_CENTER, LV_FLEX_ALIGN_CENTER);
    lv_obj_set_style_pad_row(p->busy, 14, 0);
    if (p->tool_line) lv_obj_move_to_index(p->busy, 0);   // verb first, whichever was created first
    p->busy_icon = NULL;                                 // no sparkle — the LED ring is the loading cue
    p->busy_verb = lv_label_create(p->busy);            // "<verb> <elapsed>" (green, one line)
    lv_obj_set_style_text_font(p->busy_verb, &geist_med_21, 0);
    // Amber, not the voice green. Green on this panel means live/connected/done; a turn in progress is its
    // own state and reusing the done colour makes the two indistinguishable at a glance.
    lv_obj_set_style_text_color(p->busy_verb, COL_YELLOW, 0);
    p->busy_meta = NULL;   // no stale-recap teaser here; live activity shows via tool_line when the backend sends it
    busy_compose(p);
}

// Create the empty tile container for an agent (UNpositioned — update_content_window places it at its
// current ring column). Called by materialize_content on window entry; free_content deletes the whole tile
// on exit, so a far-off agent holds ZERO LVGL objects (the spacer reserves the whole virtual scroll range).
static void create_tile(proj_t *p)
{
    if (p->tile) return;
    p->tile = lv_obj_create(tileview);
    lv_obj_set_size(p->tile, carousel_w(), carousel_h());
    lv_obj_set_style_border_width(p->tile, 0, 0);
    lv_obj_set_style_radius(p->tile, 0, 0);
    // Warm, like the page on it. Everything on this tile except the action bar is part of the reading
    // surface now, so leaving the ground at pure black would put a cold frame around a warm sheet.
    lv_obj_set_style_bg_color(p->tile, COL_BG, 0);
    // NO flex on the tile: each band is placed at a fixed Y and fills the 640px column. A centred flex
    // column shrinks to its content and parks in the middle, which is what made the ported layout read as
    // a cluster in a void at 720px.
    lv_obj_set_style_pad_all(p->tile, 0, 0);
    lv_obj_clear_flag(p->tile, LV_OBJ_FLAG_SCROLLABLE);
}

// Build the header shell (large centred agent name + small engine subtitle, no status pill/dot) into p->tile.
// Windowed with the content: a far-off agent has no tile at all. Both labels read from the model so they
// rebuild correctly after free_content deletes the tile outside the active window.
// Engine badge = product mark. Claude is a recolored monochrome mask; other marks retain the exact
// colors from the same vendored assets used by the web app.
static void apply_engine_label(proj_t *p)
{
    if (!s_hdr_engine || !s_hdr_engine_txt || !proj_is_active(p)) return;
    const lv_image_dsc_t *src = engine_mark_for(p->engine);
    bool recolor = !strcmp(p->engine, "claude");
    lv_obj_add_flag(s_hdr_engine_txt, LV_OBJ_FLAG_HIDDEN);   // product-mark path only
    if (src) {
        lv_image_set_src(s_hdr_engine, src);
        // Box = exactly one pill, artwork CENTRED inside it. Sizing the box to the zoomed bitmap instead
        // left it a pixel or two off the pills (integer rounding in the scale), and the row's flex centring
        // then split that difference — the mark read as sitting high next to the boxes. Pinning the box to
        // the pill height makes the row one band by construction, whatever the font or padding become.
        lv_image_set_inner_align(s_hdr_engine, LV_IMAGE_ALIGN_CENTER);
        lv_image_set_pivot(s_hdr_engine, (int32_t)src->header.w / 2, (int32_t)src->header.h / 2);
        // 1:1 — LV_SCALE_NONE, where the reference scales the 20px asset up to the pill height. That is
        // the one place its own rule ("draw images 1:1, size the BOX not the bitmap") is broken, and it
        // is the most expensive place to break it: this mark lives in the status band, the band sits
        // over the carousel, and the carousel invalidates the band on EVERY frame of a swipe. Any scale
        // other than 256 puts the image on LVGL's software transform path — and the Claude mark is also
        // recoloured, so the two combine into lv_draw_sw_img's transform_and_recolor, per frame.
        //
        // ⚠️ MEASURED, and it did NOT move the needle: 2339 → 2408 kpx per CPU-second on the same
        // benchmark with three projects, which is inside the run-to-run spread. The transform was a
        // good suspect and it was not the culprit — a 20×20 image is 400 pixels out of the ~184,000 a
        // swipe frame redraws, so even an expensive path over it cannot show up. Recorded because the
        // next person will suspect the same thing and deserves to be told it was already tried.
        //
        // Kept anyway: it is what the layout rules say to do, it costs nothing, and it removes a
        // per-draw temp allocation from a screen whose pool is the thing that fails under pressure.
        //
        // The box stays a full pill high with the artwork centred in it, so the row still reads as one
        // band; the mark is simply 20px inside a 28px box now. The mockup's finding says the same thing
        // in one line: "Six pixels is not worth a per-frame transform."
        lv_image_set_scale(s_hdr_engine, LV_SCALE_NONE);
        lv_obj_set_size(s_hdr_engine, ctl_pill_h(), ctl_pill_h());
        lv_obj_set_style_image_recolor(s_hdr_engine, COL_CLAUDE, 0);
        // Reset this on every engine change: the same LVGL image object may previously have shown Claude.
        lv_obj_set_style_image_recolor_opa(s_hdr_engine, recolor ? LV_OPA_COVER : LV_OPA_TRANSP, 0);
        lv_obj_clear_flag(s_hdr_engine, LV_OBJ_FLAG_HIDDEN);
    } else {
        lv_obj_add_flag(s_hdr_engine, LV_OBJ_FLAG_HIDDEN);
    }
}

static void projects_loaded_cb(lv_event_t *e) { (void)e; hdr_agent_paint(); }

// Put the ACTIVE agent's identity in the header band, or hand the band back to the machine eyebrow when
// the visible page is not an agent (Overview / Machines).
static void hdr_agent_paint(void)
{
    if (!s_hdr_name || !s_hdr_ctl || !s_band_machine) return;
    // Off the projects screen this must do NOTHING. It is called from ui_project_set_name(), which the 60s
    // poll runs for every agent — so without this guard, sitting on Settings for a minute would hide the
    // name and both chips and reveal the machine eyebrow, and the tile you swiped back to would be blank
    // until you swiped to a different one. The band is not visible there anyway; SCREEN_LOADED repaints it.
    if (lv_screen_active() != scr_projects) return;
    bool on_agent = !s_overview_active && s_active_idx >= 0 && s_active_idx < s_proj_count;
    set_hidden(s_hdr_name, !on_agent);
    set_hidden(s_band_machine, on_agent);
    // The reference gates the chip row on the machine being REMOTE, because that is the only place a
    // runtime model/effort profile applies to it. Here a project always has a model, so the gate is just
    // AGENT_CTL_CHIPS — and the chips hide themselves when the value behind them is empty.
    bool chips = on_agent && AGENT_CTL_CHIPS;
    set_hidden(s_hdr_ctl, !chips);
    if (!on_agent) return;
    proj_t *p = &s_proj[s_active_idx];
    lv_label_set_text(s_hdr_name, p->name[0] ? p->name : "\xE2\x80\xA6");   // model name, or "…" placeholder
    apply_engine_label(p);
    model_chip_paint(p);
    effort_chip_paint(p);
}

// Build the content subtree (body + list + card/empty + optional busy row) from the model. No-op if
// already live. tool_line/agents/todo are NOT rebuilt — they stream from the next live event.
static void materialize_content(int i)
{
    proj_t *p = &s_proj[i];
    if (p->content_live) return;
    // Voice mode: the overlay is up and we deliberately keep ALL content freed so the PCM upload has
    // internal-RAM headroom. Don't let a swipe / live event re-materialize it mid-upload — it rebuilds
    // when voice_overlay_set(false) hides the overlay and calls update_content_window.
    if (s_voice_overlay && !lv_obj_has_flag(s_voice_overlay, LV_OBJ_FLAG_HIDDEN)) return;

    if (!p->tile) create_tile(p);      // windowed: build the empty tile on entry (positioned by update_content_window)
    if (!p->tile) return;              // pool exhausted → skip (extremely unlikely with the window bounded)
    p->dot = NULL;    // recap design drops the status dot (its only reader is guarded)

    // THE WELL — fixed position AND height, not LV_SIZE_CONTENT. Content-sizing let the recap card shrink
    // to its text and float; fixed means the frame is identical for a one-line answer, a ten-line one, and
    // a running turn.
    p->body = lv_obj_create(p->tile);
    lv_obj_remove_style_all(p->body);
    lv_obj_set_size(p->body, SETTINGS_ROW_W, WELL_H);
    lv_obj_align(p->body, LV_ALIGN_TOP_MID, 0, WELL_Y);
    lv_obj_set_flex_flow(p->body, LV_FLEX_FLOW_COLUMN);
    lv_obj_set_flex_align(p->body, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_START);
    lv_obj_set_style_pad_row(p->body, 12, 0);
    lv_obj_clear_flag(p->body, LV_OBJ_FLAG_SCROLLABLE);

    p->list = lv_obj_create(p->body);
    lv_obj_remove_style_all(p->list);
    lv_obj_set_width(p->list, lv_pct(100));
    lv_obj_set_height(p->list, lv_pct(100));      // fill the well so the card can too
    lv_obj_set_flex_flow(p->list, LV_FLEX_FLOW_COLUMN);
    lv_obj_set_flex_align(p->list, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_START);
    lv_obj_set_style_pad_row(p->list, WELL_ROW_GAP, 0);
    lv_obj_clear_flag(p->list, LV_OBJ_FLAG_SCROLLABLE);

    if (p->m_preview) render_event_card(p, p->m_preview, p->m_full, p->m_col);
    else p->empty = make_label(p->list, "No activity yet", COL_INK_LOW, &geist_reg_25);

    if (p->busy_model) {                         // a turn is processing → show the Working… row, hide card
        lv_obj_add_flag(p->list, LV_OBJ_FLAG_HIDDEN);
        render_busy_row(p);
    }
    p->content_live = true;
}

// Tear down the content subtree (frees the whole body subtree incl. the event card, whose DELETE cb
// frees its stashed full text). The model (m_preview/m_full/busy_model) is preserved for re-entry.
static void free_content(int i)
{
    proj_t *p = &s_proj[i];
    if (!p->content_live) return;
    if (p->tile) { lv_obj_delete(p->tile); p->tile = NULL; }   // delete the WHOLE tile → 0 objects for a far agent
    p->body = p->list = p->empty = p->recap_lbl = p->sum_box = NULL;
    p->busy = p->busy_verb = p->busy_meta = p->busy_icon = NULL;
    p->tool_line = p->agents = p->todo = p->todo_active = NULL;
    p->dot = NULL;
    p->content_live = false;
}

// Instrumentation (gated off): log LVGL's 64KB pool usage on every window change. Verified free bytes stay
// flat while swiping — materialize/free bounded, no leak. Flip to 1 to re-check pool health.
#define LAZY_MEM_DEBUG 0

// Position + materialize the ~CONTENT_WINDOW columns around the centered column; free everything outside.
// Columns map CIRCULARLY to ring positions (ring_of_col): ring 0 = Settings, ring r>0 = agent[r-1]. Each
// window column gets the right tile placed at col*W. An agent whose column left the window is freed → 0
// objects. Idempotent + cheap — call after any scroll settle / add / remove. Caller holds the lock.
static void update_content_window(void)
{
    int32_t w = carousel_w();
    int cc = carousel_col();

    // 1. Free every agent that no longer belongs in the window: its column drifted out (|tile_col-cc|), OR
    //    the ring at its column no longer maps to it (N changed → the modulo remapped that column to a
    //    different agent). Without the ring check, adding agents (which shifts N+1) would pile stale tiles
    //    at the same columns and leak the pool.
    for (int i = 0; i < s_proj_count; i++) {
        if (s_proj[i].content_live) {
            int d = s_proj[i].tile_col - cc; if (d < 0) d = -d;
            if (d > CONTENT_WINDOW || ring_of_col(s_proj[i].tile_col) != ring_of_agent(i)) free_content(i);
        }
    }

    // 2. Materialize + position the right tile for each window column. A fixed tile (Overview, or the
    //    "No projects" page) can map to MULTIPLE window columns when there are few projects (tiny ring);
    //    pick the column CLOSEST to centre so it's never shoved off-screen.
    bool noagents_shown = false, overview_shown = false;
    int noagents_col = cc, noagents_best = CONTENT_WINDOW + 1;
    int overview_col = cc, overview_best = CONTENT_WINDOW + 1;
    for (int dc = -CONTENT_WINDOW; dc <= CONTENT_WINDOW; dc++) {
        int col = cc + dc;
        int r = ring_of_col(col);
        int ad = dc < 0 ? -dc : dc;
        if (r == 0) {                                   // overview page (leading, ring 0)
            if (ad < overview_best) { overview_best = ad; overview_col = col; }
            overview_shown = true;
        } else if (s_proj_count == 0) {                 // no projects → ring RING_LEAD is the empty page
            if (ad < noagents_best) { noagents_best = ad; noagents_col = col; }
            noagents_shown = true;
        } else {                                        // agent at this column
            int ai = agent_of_ring(r);
            if (ai >= 0 && ai < s_proj_count) {
                proj_t *p = &s_proj[ai];
                if (!p->content_live) materialize_content(ai);
                if (p->tile) { lv_obj_set_x(p->tile, col * w); p->tile_col = col; }
            }
        }
    }
    // No-projects tile: shown at the centre-most ring-RING_LEAD column when there are none, else hidden.
    if (noagents_shown && s_no_agents_tile) {
        lv_obj_set_x(s_no_agents_tile, noagents_col * w);
        lv_obj_clear_flag(s_no_agents_tile, LV_OBJ_FLAG_HIDDEN);
    } else if (s_no_agents_tile) {
        lv_obj_add_flag(s_no_agents_tile, LV_OBJ_FLAG_HIDDEN);
    }
    // Overview tile (leading ring 0): symmetric to the other persistent fixed tiles.
    if (overview_shown && s_overview_tile) {
        lv_obj_set_x(s_overview_tile, overview_col * w);
        lv_obj_clear_flag(s_overview_tile, LV_OBJ_FLAG_HIDDEN);
    } else if (s_overview_tile) {
        lv_obj_add_flag(s_overview_tile, LV_OBJ_FLAG_HIDDEN);
    }

#if LAZY_MEM_DEBUG
    int live = 0;
    for (int i = 0; i < s_proj_count; i++) if (s_proj[i].content_live) live++;
    lv_mem_monitor_t mon; lv_mem_monitor(&mon);
    ESP_LOGI(TAG, "lvmem free=%u biggest=%u used=%d%% frag=%d%% | projects=%d live=%d cc=%d ring=%d",
             (unsigned)mon.free_size, (unsigned)mon.free_biggest_size, (int)mon.used_pct,
             (int)mon.frag_pct, s_proj_count, live, cc, ring_of_col(cc));
#endif
}

// Small-ring smoothing — ONLY the 1-agent ring (ring_len == 2). With a single agent the ring has just two
// positions (0 = Settings, 1 = agent), so BOTH window neighbours of any tile map to the SAME entity, but
// each entity owns one physical tile → one side stays blank until SCROLL_END rebuilds it. That blank-then-
// pop is the stutter when swiping off Settings. Fix WITHOUT breaking the infinite ring and WITHOUT
// duplicating tiles: on every scroll frame, pin each of the (at most) two columns overlapping the viewport
// to its ring entity's single tile. The two visible columns are ADJACENT → opposite parity → always
// DIFFERENT entities (one Settings, one agent), so the two single tiles never contend, and the tile a drag
// moves away from is 2 columns off (off-screen) at the moment it's relocated → the move is invisible.
// Also covers N==0 (ring_len 2 now: Settings + the "No agents" page). N>=2 (ring_len>=3 already fills the
// ±CONTENT_WINDOW window with distinct tiles) is untouched.
static void carousel_cover_leading(void)
{
    if (ring_len() != 2) return;                     // the 1-agent AND empty rings collide in the window
    int32_t w = carousel_w();
    if (w <= 0) return;
    int32_t sx = lv_obj_get_scroll_x(tileview);
    int c0 = (int)(sx / w);                           // left visible column (sx is deep-positive mid-ring)
    for (int col = c0; col <= c0 + 1; col++) {        // the up-to-two columns overlapping the viewport
        int r = ring_of_col(col);
        if (r == 0) {                                 // Overview page
            if (s_overview_tile) {
                lv_obj_set_x(s_overview_tile, col * w);
                lv_obj_clear_flag(s_overview_tile, LV_OBJ_FLAG_HIDDEN);
            }
        } else if (s_proj_count == 0) {               // no projects → ring 1 is the empty page
            if (s_no_agents_tile) {
                lv_obj_set_x(s_no_agents_tile, col * w);
                lv_obj_clear_flag(s_no_agents_tile, LV_OBJ_FLAG_HIDDEN);
            }
        } else {                                      // agent r-1 (kept materialized as a neighbour when N==1)
            int ai = r - 1;
            if (ai >= 0 && ai < s_proj_count) {
                proj_t *p = &s_proj[ai];
                if (!p->content_live) materialize_content(ai);
                if (p->tile) { lv_obj_set_x(p->tile, col * w); p->tile_col = col; }
            }
        }
    }
}

static void carousel_scroll(lv_event_t *e) { (void)e; carousel_cover_leading(); }

// Voice mode: show the dark overlay and FREE every tile's content (frees the LVGL/internal RAM the WS
// TLS upload needs — the heavy UI otherwise leaves ~12KB internal and the PCM upload drops the socket).
// Turning it off restores the active tile ± window. Caller holds the display lock.
static void voice_overlay_set(bool on)
{
    if (s_voice_overlay) set_hidden(s_voice_overlay, !on);
    act_bar_apply();   // the overlay owns the screen while recording — take the bar out from under it
    if (on) {
        for (int i = 0; i < s_proj_count; i++) free_content(i);
    } else {
        update_content_window();
    }
}

// Remove a project's tile (its session ended and the tmux pane is gone). Deletes the tile's LVGL
// subtree, shifts the model over the hole, re-columns the remaining tiles so the swipe stays
// gap-free, rebuilds the trailing settings tile, and re-focuses a valid tile. Safe if id is unknown.
void ui_project_remove(const char *project_id)
{
    if (!project_id) return;
    char active_id[48];
    snprintf(active_id, sizeof(active_id), "%s", ui_get_active_project_id());
    bool voice_aborted = active_id[0] && strcmp(active_id, project_id) == 0 && voice_active();
    if (voice_aborted) voice_abort();

    display_lock();
    int i = find_proj(project_id);
    if (i < 0) { display_unlock(); return; }
    // Process lifetime wins over transient UI: a removed project that was being spoken to cannot leave
    // the capture overlay up. The reference kept this in a helper because it also had to dismiss an
    // AskUserQuestion screen for the same project; with that screen gone there is one thing left to do
    // and the helper was longer than its body.
    if (voice_aborted) {
        s_voice_routing = false;
        s_voice_route_ms = 0;
        voice_icon_apply(VIC_NONE);
        voice_overlay_set(false);
        update_stop_btn();
    }

    // Capture the page centered NOW (old modulo) so we keep viewing the SAME agent after the shift + remodulo.
    // By id, because delete shifts indices; if the removed agent itself was centered, we land on a neighbour.
    int cc_ring = ring_of_col(carousel_col());
    char keep_id[48] = "";
    if (cc_ring >= RING_LEAD && cc_ring < ring_agents_end())   // on a project tile
        snprintf(keep_id, sizeof keep_id, "%s", s_proj[agent_of_ring(cc_ring)].id);

    // Windowed model: free EVERY materialized agent tile first so the model shift below can't strand a tile
    // at a stale column — update_content_window rebuilds the window at the new columns. Free the removed
    // agent's PSRAM strings too (free_content only tears down LVGL, it preserves the model strings).
    for (int k = 0; k < s_proj_count; k++) free_content(k);
    free(s_proj[i].m_preview);
    free(s_proj[i].m_full);

    // Shift the model down over the hole, then clear the vacated slot (pointers now live below it).
    for (int k = i; k < s_proj_count - 1; k++) s_proj[k] = s_proj[k + 1];
    s_proj_count--;
    memset(&s_proj[s_proj_count], 0, sizeof(proj_t));

    resize_spacer();           // scroll range shrank by one column
    rebuild_overview_tile();

    // Re-anchor: keep the same page centered under the new modulo. The viewed project → its NEW index
    // (re-found by id). If the removed project WAS centered → whichever now occupies its slot (clamped
    // to the last). The last one leaving lands on the empty page.
    int target_ring;                           // ring_of_agent() now uses the NEW (reduced) N
    if (s_proj_count == 0) {
        target_ring = ring_of_agent(0);        // empty slot at RING_LEAD = the "No projects" page
    } else {
        int ni = find_proj(keep_id);
        int ai = (ni >= 0) ? ni : (i < s_proj_count ? i : s_proj_count - 1);
        target_ring = ring_of_agent(ai);       // project index → ring
    }
    carousel_goto(col_for_ring_near(carousel_col(), target_ring), LV_ANIM_OFF);
    apply_active_from_col();
    update_content_window();
    display_unlock();
}

void ui_project_clear_all(void)
{
    display_lock();
    for (int i = 0; i < s_proj_count; i++) {
        free_content(i);
        free(s_proj[i].m_preview);
        free(s_proj[i].m_full);
    }
    memset(s_proj, 0, MAX_PROJECTS * sizeof(*s_proj));
    s_proj_count = 0;
    resize_spacer();
    rebuild_overview_tile();
    rebuild_page_dots();
    carousel_goto(col_for_ring_near(carousel_col(), 0 /* overview */), LV_ANIM_OFF);
    apply_active_from_col();
    update_content_window();
    display_unlock();
}

// Create a tile for a new project (caller holds the lock). Returns index or -1 if full.
static int add_proj(const char *id)
{
    if (s_proj_count >= MAX_PROJECTS) return -1;
    // Adding a project grows the ring (N+1), which remaps EVERY column → the page you're viewing would
    // jump. Capture the ring centered now (old modulo) and re-anchor to it under the new one below.
    // Project indices don't shift on append, so the ring value still identifies the same page.
    int cc_ring = (s_proj_count > 0) ? ring_of_col(carousel_col()) : -1;
    int  on_agent    = (cc_ring >= RING_LEAD && cc_ring < ring_agents_end()) ? agent_of_ring(cc_ring) : -1;
    bool keep_remote_reload_page = s_remote_online_reload &&
        (lv_screen_active() != scr_projects || !s_overview_active);
    int i = s_proj_count++;
    proj_t *p = &s_proj[i];
    snprintf(p->id, sizeof(p->id), "%s", id);
    p->busy = NULL;

    // No tile yet — create_tile + content are built lazily by materialize_content ONLY while
    // this agent is inside the active window, and the whole tile is deleted when it leaves. A far-off agent
    // therefore holds ZERO LVGL objects; the spacer (resize_spacer) reserves its scroll column so scroll
    // positions stay absolute. The 64KB pool is bounded at ANY agent count → truly unlimited.
    resize_spacer();           // (re)assert the huge fixed scroll range
    rebuild_overview_tile();
    rebuild_page_dots();
    // First project → jump scroll to the MIDDLE of the huge range BEFORE windowing, so the window
    // materializes around where we actually are (not around column 0). During a reconnect reload, stay on
    // Overview if the user had already swiped away from it; ui_land_after_reload owns the final focus.
    if (i == 0) {
        int tr = keep_remote_reload_page ? 0 /* overview */ : ring_of_agent(0);
        carousel_goto(col_for_ring_near(CAROUSEL_M / 2, tr), LV_ANIM_OFF);
    } else {
        int tr = on_agent >= 0 ? ring_of_agent(on_agent) : 0 /* overview */;
        carousel_goto(col_for_ring_near(carousel_col(), tr), LV_ANIM_OFF);
    }
    apply_active_from_col();
    update_content_window();   // materialize the window at the current scroll column
    return i;
}

