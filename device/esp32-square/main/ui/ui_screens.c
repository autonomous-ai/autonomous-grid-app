// Codepoints geist_reg_13 actually contains (ASCII + Vietnamese + a few symbols). Anything else
// (CJK, emoji, …) has no glyph; rendering such text could read a bad glyph bitmap and corrupt the
// heap — and it shows as tofu anyway — so we strip them.
static bool cp_in_font(uint32_t cp)
{
    if (cp == '\n' || cp == '\t') return true;
    if (cp >= 0x20 && cp <= 0x7E) return true;        // ASCII
    if (cp >= 0xA0 && cp <= 0x24F) return true;       // Latin-1 + Extended-A/B (đ ơ ư …)
    if (cp >= 0x1E00 && cp <= 0x1EFF) return true;    // Latin Extended Additional (Vietnamese)
    if (cp >= 0x2013 && cp <= 0x2026) return true;    // – — ' ' " " …
    if (cp == 0x203A || cp == 0x2713 || cp == 0x2717) return true; // › ✓ ✗
    return false;
}

// Copy `s` to `out` (≤cap) keeping only UTF-8 chars the font can render; collapse runs of dropped
// chars to a single space so words don't run together.
static void utf8_filter(const char *s, char *out, size_t cap)
{
    size_t o = 0; bool gap = false;
    while (*s && o + 5 < cap) {
        unsigned char c = (unsigned char)*s;
        int len; uint32_t cp;
        if (c < 0x80)            { cp = c;        len = 1; }
        else if ((c & 0xE0) == 0xC0) { cp = c & 0x1F; len = 2; }
        else if ((c & 0xF0) == 0xE0) { cp = c & 0x0F; len = 3; }
        else if ((c & 0xF8) == 0xF0) { cp = c & 0x07; len = 4; }
        else { s++; continue; }
        bool ok = true;
        for (int k = 1; k < len; k++) { if ((((unsigned char)s[k]) & 0xC0) != 0x80) { ok = false; break; } cp = (cp << 6) | (s[k] & 0x3F); }
        if (!ok) { s++; continue; }
        if (cp_in_font(cp)) {
            if (gap && o + 1 < cap) { out[o++] = ' '; gap = false; }
            for (int k = 0; k < len && o + 1 < cap; k++) out[o++] = s[k];
        } else if (o > 0) {
            gap = true; // remember we dropped something between kept chars
        }
        s += len;
    }
    out[o] = '\0';
}

// Truncate to at most `max` bytes without splitting a UTF-8 sequence.
static int utf8_clip(const char *s, int max)
{
    int n = (int)strlen(s);
    if (n <= max) return n;
    int i = max;
    while (i > 0 && ((unsigned char)s[i] & 0xC0) == 0x80) i--;
    return i;
}

// Marker + colour for a commander event kind. Markers are Unicode glyphs included in geist_reg_13
// (the custom font has no FontAwesome symbols).
static void kind_style(const char *kind, const char **sym, lv_color_t *col)
{
    if (kind && !strcmp(kind, "act"))        { *sym = "\xE2\x80\xBA ";  *col = COL_ACCENT; } // ›
    else if (kind && !strcmp(kind, "ask"))   { *sym = "? ";             *col = COL_YELLOW; }
    else if (kind && !strcmp(kind, "done"))  { *sym = "\xE2\x9C\x93 ";  *col = COL_GREEN;  } // ✓
    else if (kind && !strcmp(kind, "summary")){ *sym = "";               *col = COL_FG;     } // turn summary = main readable content (neutral, not alarming green)
    else if (kind && !strcmp(kind, "error")) { *sym = "\xE2\x9C\x97 ";  *col = COL_RED;    } // ✗
    else                                     { *sym = "";               *col = COL_FG;     } // say
}

// Drop the transient "processing" dot row (if any) and restore the event card to full opacity.
// The card is faded while processing so the blinking dots stand out; this un-fades it. Caller holds lock.
static void clear_busy(proj_t *p)
{
    p->busy_model = false;   // model: turn is no longer processing (matters for off-window tiles too)
    if (p->tool_line) { lv_obj_delete(p->tool_line); p->tool_line = NULL; }  // drop the current-tool row
    if (p->agents) { lv_obj_delete(p->agents); p->agents = NULL; }  // drop the sub-agent list (turn ended → summary replaces it)
    if (p->busy) { lv_obj_delete(p->busy); p->busy = NULL; }  // deletes the two child labels too
    p->busy_verb = NULL; p->busy_meta = NULL; p->busy_icon = NULL; p->busy_last_ms = 0;
    if (p->todo) { lv_obj_delete(p->todo); p->todo = NULL; p->todo_active = NULL; }  // drop the checklist
    if (p->list) { lv_obj_clear_flag(p->list, LV_OBJ_FLAG_HIDDEN); lv_obj_set_style_opa(p->list, LV_OPA_COVER, 0); }
    // No tile relayout to undo: render_busy_row no longer moves the frame. The "set in TWO places, a
    // mismatch shifts the tile after every turn" hazard is gone rather than managed.
    overview_working_apply();   // this agent stopped working → refresh the Overview "N working" count
}


// Reap orphaned busy tiles by heartbeat absence. A tile goes/stays "Working…" only via a live 'processing'
// frame; the ONLY thing that clears it is a live terminal event (summary/done/error). That terminal can be
// lost (WS drop right as the turn ends) or never produced at all (turn completed while the adapter was
// restarting → hydrated silently), and history replay never clears busy (project_apply_event's !restored
// guard) — so the tile would spin forever. Backstop: while a turn is live, BOTH the adapter and the VM node
// re-emit 'processing' every ~5s (turn heartbeat), covering the turn AND the trailing "Summarizing…" window.
// Each such frame stamps busy_last_ms. If the stamps stop for > BUSY_TIMEOUT the turn is gone (ended, or the
// link died) → clear. Safe because a genuinely-live turn keeps stamping every 5s; only silence clears. Called
// from the ~1s refresh loop. Returns #cleared.
int ui_prune_stale_busy(void)
{
    // 25s ≈ 5 turn-heartbeats — tolerates 2-3 missed beats before deciding the turn is gone. Firing early
    // wrongly clears a live turn; waiting costs nothing (the busy was stuck forever without this) → bias large.
    const int64_t BUSY_TIMEOUT_US = 25LL * 1000000LL;
    int cleared = 0;
    display_lock();
    int64_t now = esp_timer_get_time();
    for (int i = 0; i < s_proj_count; i++) {
        proj_t *p = &s_proj[i];
        if (!p->busy_model) { p->busy_last_ms = 0; continue; }
        if (p->busy_last_ms == 0) { p->busy_last_ms = now; continue; } // busy set without a stamp yet → arm it
        if (now - p->busy_last_ms < BUSY_TIMEOUT_US) continue;         // still receiving heartbeats → live turn
        ESP_LOGW(TAG, "prune stale busy: agent=%s silent %llds — no heartbeat, clearing",
                 p->id[0] ? p->id : "?", (long long)((now - p->busy_last_ms) / 1000000));
        clear_busy(p);
        cleared++;
    }
    display_unlock();
    return cleared;
}





// Apply either a live commander event or a persisted historical recap. A restored recap updates the
// card underneath Working but must never own/clear the live turn lifecycle.
static void project_apply_event(const char *project_id, const char *kind,
                                const char *text, const char *recap, bool restored)
{
    const char *pid = (project_id && project_id[0]) ? project_id : "(none)";
    display_lock();
    int i = find_proj(pid);
    if (i < 0) i = add_proj(pid);
    if (i < 0) { display_unlock(); return; }
    proj_t *p = &s_proj[i];

    bool live = p->content_live;   // is this tile's content on-screen? if not, we only update the model

    // "processing" is a transient status (server 2s heartbeat / "Summarizing…"), NOT a ring-buffer
    // event. It flips the model's busy flag; the Working… row (orange gerund + grey elapsed·tokens) is
    // built from the model — now if this tile is materialized, else when it's swiped into. Cleared the
    // moment a real event lands. Rows updated by busy_dots_tick (elapsed 1s / verb 6s).
    if (kind && strcmp(kind, "processing") == 0) {
        if (restored) { display_unlock(); return; }   // never resurrect transient state from history
        bool started = !p->busy_model;
        if (started) { p->busy_model = true; p->busy_since = esp_timer_get_time(); p->busy_step[0] = '\0'; overview_working_apply(); }
        // `text` on a processing frame is the step the agent is on, or empty to fall back to the gerund.
        if (text) utf8_filter(text, p->busy_step, sizeof(p->busy_step));
        // Live proof-of-life: stamp the time of this 'processing' frame. Both the turn (Processing) and the
        // trailing summarize (Summarizing…) heartbeat here every ~5s; ui_prune_stale_busy() clears the tile
        // if the stamps stop arriving (a terminal event was lost or never produced), so busy never wedges.
        p->busy_last_ms = esp_timer_get_time();
        if (live) {
            render_busy_row(p);                                          // no-op if already built
            if (p->list) lv_obj_add_flag(p->list, LV_OBJ_FLAG_HIDDEN);   // hide the card; only the working row shows
            update_stop_btn();
        }
        display_unlock();
        return;
    }
    // Only a LIVE real event (summary/done/error/…) ends the turn. Historical recap can race a freshly
    // replayed processing frame after machine selection; keep Working visible and update its hidden card.
    if (!restored) {
        p->busy_model = false;
        p->busy_step[0] = '\0';
        if (live) { clear_busy(p); update_stop_btn(); }
        overview_working_apply();   // turn ended → drop the Overview "N working" count (live or off-window)
    }

    // A bare terminal 'done' (generic fallback the backend sends when NO turn-summary was produced) is
    // only a signal to clear the "Processing" status — not readable content. Keep the last real card.
    if (kind && strcmp(kind, "done") == 0 && (!text || !text[0] || strcmp(text, "done") == 0)) {
        display_unlock();
        return;
    }

    const char *sym; lv_color_t col;
    kind_style(kind, &sym, &col);
    const char *body = (text && text[0]) ? text : (kind ? kind : "");
    // Scratch in PSRAM (~5.3KB off internal RAM): all four fields are used within this one call, which
    // runs on the small commander WS task and is serialized under display_lock. Was static .bss; on the
    // stack it overflowed and smashed the return address (crash on long events), hence the shared buffer.
    static struct emit_scratch { char clean[2100]; char full[2160]; char preview[520]; char recap_clean[512]; } *s_emit;
    if (!s_emit) s_emit = ram_psram_alloc(sizeof(*s_emit), "event_format_scratch");
    if (!s_emit) { display_unlock(); return; }   // PSRAM exhausted (never in practice) → bail, don't crash
    char *clean = s_emit->clean, *full = s_emit->full, *preview = s_emit->preview, *recap_clean = s_emit->recap_clean;
    utf8_filter(body, clean, sizeof(s_emit->clean));          // drop glyphs the font can't render (CJK/emoji)
    snprintf(full, sizeof(s_emit->full), "%s%s", sym, clean); // marker + renderable text (for the reader)

    // Tile shows a short preview; when a `recap` headline is provided (summary card) show it IN FULL,
    // otherwise clip `full` as a teaser.
    const char *preview_src = full;
    int limit = PREVIEW_BYTES;
    bool has_recap = false;
    if (recap && recap[0]) {
        utf8_filter(recap, recap_clean, sizeof(s_emit->recap_clean));  // drop unrenderable glyphs
        if (recap_clean[0]) { preview_src = recap_clean; limit = (int)sizeof(s_emit->preview) - 8; has_recap = true; }
    }
    int plen = utf8_clip(preview_src, limit);
    memcpy(preview, preview_src, plen);
    if ((int)strlen(preview_src) > plen) { memcpy(preview + plen, "\xE2\x80\xA6", 3); plen += 3; } // …
    preview[plen] = '\0';

    // Update atomically so a PSRAM OOM never discards the previous readable recap.
    char *next_preview = dup_str(preview);
    char *next_full = dup_str(full);
    if (!next_preview || !next_full) {
        free(next_preview);
        free(next_full);
        display_unlock();
        return;
    }
    // Snapshot BEFORE the model is overwritten — the dedup below used to read the old card's user_data,
    // which nothing writes any more. Left dead it would rebuild the box on every repeated event, and a
    // rebuild throws the scroll position back to the top. That box is now the only place long text is
    // read, so that is the user yanked to the top mid-sentence.
    bool same_event = p->m_full && strcmp(p->m_full, full) == 0;
    free(p->m_preview); p->m_preview = next_preview;
    free(p->m_full);    p->m_full = next_full;
    p->m_has_recap = has_recap;   // no recap → one zone, not two (the headline would repeat the body)
    p->m_col = col;

    if (!live) {
        // Off-window: the model is enough; the card renders when the agent's column enters the window.
        // If this agent IS currently in the visible window (e.g. freshly added), the refresh materializes it.
        update_content_window();
        display_unlock();
        return;
    }

    // Live render into the on-screen list. Drop the placeholder, dedup an exact repeat (the backend can
    // emit the same event twice), trim to MAX_EVENTS, then draw the card.
    if (p->empty) { lv_obj_delete(p->empty); p->empty = NULL; }
    if (same_event && p->sum_box) { display_unlock(); return; }   // identical repeat → keep the scroll
    while (p->list && lv_obj_get_child_count(p->list) > 0) {
        lv_obj_t *oldest = lv_obj_get_child(p->list, 0);
        if (!oldest) break;
        lv_obj_delete(oldest);
    }
    p->recap_lbl = p->sum_box = NULL;   // both just went with the children — free_content's invariant
    render_event_card(p, preview, full, col);
    display_unlock();
}

// Append a live event to a project's tile, keeping only the last MAX_EVENTS.
//
