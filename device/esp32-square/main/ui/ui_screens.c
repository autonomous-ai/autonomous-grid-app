        lv_label_set_text(nm, n->name[0] ? n->name : n->proj_id);
        lv_obj_t *tm = lv_label_create(nmrow);   // small muted time on the right
        lv_obj_set_style_text_font(tm, &lv_font_montserrat_14, 0);
        lv_obj_set_style_text_color(tm, COL_INK_LOW, 0);
        char tb[12]; notif_rel_time(n->ms, tb, sizeof tb);
        lv_label_set_text(tm, tb);
        // THE PAYLOAD. It gets the body face — the same geist_reg_24 the well uses for "the answer you
        // read" — because that is exactly what this is. The name above it was the same size until now,
        // which made a card read as two equal lines instead of a label over its content. The mockup asks
